// `/health` отвечает ДО проверки ключа, и это правильно: на него смотрят и приёмка
// выката, и состояние обмена в дашборде, а ключа у них нет. Но считался ответ обходом
// каталога с разбором JSON каждого среза — то есть самый дешёвый неавторизованный
// запрос заставлял ноду перечитать все срезы, и повторять это можно было сколько
// угодно. Теперь ответ лежит готовым: TTL плюс явный сброс при приёме среза и чистке,
// чтобы `installs`/`last` не отставали от факта. Формат ответа не меняется — на него
// опираются приёмочные проверки.
let healthCache = { at: 0, body: null };
function healthBody() {
    const now = Date.now();
    if (healthCache.body && now - healthCache.at < HEALTH_TTL_MS) return healthCache.body;
    const all = allSlices();
    healthCache = { at: now, body: { ok: true, installs: all.length,
        last: all.map(p => p.recvAt).sort().pop() || null } };
    return healthCache.body;
}

// ── Чистка срез-файлов ──────────────────────────────────────────────────────
// Срез-файлы не удалялись НИКОГДА: каждый новый installId — новый файл, а устаревшие
// только скрывались из `/peers` (STALE_MS). Держатель ключа с циклом на смену id
// заливал ноде тысячи файлов — иноды и место, — и заметить это было неоткуда. Порог
// щедрый намеренно: полгода без единого среза. Месяц-другой без включённой машины —
// нормальная жизнь, выкидывать за это нельзя; полгода — это уже не «в отпуске», а
// другой installId после переустановки. Метём не чаще раза в час: обход каталога на
// каждый запрос — ровно то, за что выше поругана `/health`.
let sweptAt = 0;
function sliceSweep(force) {
    const now = Date.now();
    if (!force && now - sweptAt < SLICE_SWEEP_MS) return 0;
    sweptAt = now;
    let names = [], gone = 0;
    try { names = fs.readdirSync(SLICES); } catch { return 0; }
    for (const f of names) {
        if (!f.endsWith('.json')) continue;
        const p = path.join(SLICES, f);
        // Возраст берём из `recvAt` самого среза, а не из mtime файла: mtime меняет
        // любое касание, а recvAt — только настоящий приём.
        const s = readSlice(f.slice(0, -5));
        const at = s ? Date.parse(s.recvAt) : NaN;
        let age;
        if (Number.isFinite(at)) age = now - at;
        else { try { age = now - fs.statSync(p).mtimeMs; } catch { continue; } }
        if (age <= SLICE_TTL_MS) continue;
        try { fs.unlinkSync(p); gone++; } catch { /* уже нет — не беда */ }
    }
    if (gone) {
        healthCache.at = 0;
        log(`убрано срез-файлов старше ${Math.round(SLICE_TTL_MS / 864e5)} дней: ${gone}`);
    }
    return gone;
}
