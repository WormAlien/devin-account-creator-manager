let saltCache = { key: '', val: '' };
function addrSalt() {
    let st;
    try { st = fs.statSync(SALT_FILE); } catch { return SECRET; }
    const key = st.mtimeMs + ':' + st.size;
    if (saltCache.key === key) return saltCache.val;
    let v = '';
    try { v = fs.readFileSync(SALT_FILE, 'utf8').trim(); } catch { /* исчез между stat и read */ }
    if (!v) return SECRET;
    saltCache = { key, val: v };
    return v;
}
