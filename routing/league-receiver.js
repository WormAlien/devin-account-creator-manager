// ── Чат: журнал, счётчик, валидаторы ────────────────────────────────────────
// Тип вложения решают БАЙТЫ, а не заголовок и не поле `mime`: mime пишет клиент,
// а сигнатуру — кодировщик. Это правило было и раньше, но знало ровно один формат —
// webp; из-за этого голосовое сообщение получало 415 и физически не могло уехать.
const magic = (b, s, off = 0) => b.length >= off + s.length
    && b.toString('latin1', off, off + s.length) === s;
// `RIFF....WEBP` — контейнер webp, четыре байта размера между ними нам не нужны.
const isWebp = b => b.length > 12 && magic(b, 'RIFF') && magic(b, 'WEBP', 8);

// Расширение → чем это отдавать. Расширение здесь ВСЕГДА наше: из этой таблицы, а не
// из строки запроса, — поэтому в путь файла ничего чужого не попадает по построению.
const ATT_KIND = {
    webp: { kind: 'image', mime: 'image/webp' },
    webm: { kind: 'audio', mime: 'audio/webm' },
    ogg: { kind: 'audio', mime: 'audio/ogg' },
    m4a: { kind: 'audio', mime: 'audio/mp4' },
    mp3: { kind: 'audio', mime: 'audio/mpeg' },
    wav: { kind: 'audio', mime: 'audio/wav' },
};
// Белый список сигнатур. Порядок значим дважды:
//   · `RIFF` начинают и webp, и wav — различает их слово на 8-м байте, поэтому оба
//     проверяются по ПОЛНОЙ сигнатуре и раньше остальных;
//   · кадровая синхронизация mp3 (`FF Ex`) — самая слабая проверка из всех (два байта,
//     из них 11 бит), поэтому она последняя и не может перекрыть формат с настоящей магией.
// Что и почему в списке: webm (EBML `1A 45 DF A3`) — это то, чем пишет голос
// MediaRecorder в Chrome, Edge и Firefox; ogg (`OggS`) — он же в Firefox и «телеграмный»
// формат голосовых; m4a (`ftyp` на 4-м байте) — Safari и iOS, там MediaRecorder отдаёт
// audio/mp4; mp3 и wav — то, что человек перетащит файлом. Форматов, которые браузер не
// сыграет (amr, flac и прочее), в списке нет намеренно: единственный потребитель этих
// байтов — вкладка дашборда, и принимать то, что она не откроет, значит копить мусор.
// Добавить формат — это одна строка здесь и одна в ATT_KIND.
const ATT_SNIFF = [
    ['webp', isWebp],
    ['wav', b => b.length > 12 && magic(b, 'RIFF') && magic(b, 'WAVE', 8)],
    ['webm', b => b.length > 16 && b[0] === 0x1A && b[1] === 0x45 && b[2] === 0xDF && b[3] === 0xA3],
    ['ogg', b => b.length > 16 && magic(b, 'OggS')],
    ['m4a', b => b.length > 16 && magic(b, 'ftyp', 4)],
    ['mp3', b => b.length > 16 && (magic(b, 'ID3') || (b[0] === 0xFF && (b[1] & 0xE0) === 0xE0))],
];
const ATT_OK = ATT_SNIFF.map(([e]) => e).join(', ');
function attSniff(buf) {
    for (const [ext, test] of ATT_SNIFF) if (test(buf)) return { ext, ...ATT_KIND[ext] };
    return null;
}
// У картинки, звука и файла разные пределы веса, и до опознания типа сравнивать не с чем —
// отсюда порядок проверок в handleChat: сначала сигнатура, потом размер.
const attMax = kind => (kind === 'audio' ? MAX_ATT_AUDIO : kind === 'file' ? MAX_ATT_FILE : MAX_ATT);
const attOctet = { kind: 'file', mime: 'application/octet-stream' };
const attExtOk = e => typeof e === 'string' && /^[a-z0-9]{1,8}$/.test(e);
const attType = ext => ATT_KIND[ext] || attOctet;
// Имя файла — НОВАЯ сущность, и оно приходит от человека. Хранится ОТДЕЛЬНО от пути: на
// диске файл по-прежнему лежит под номером сообщения, а исходное имя — поле записи журнала.
// Иначе это обход каталога прямым текстом.
// Санитайзер обязателен, и в нём не только `..` и слэши:
//   · управляющие символы, перевод строки, кавычки и точка с запятой — иначе они уедут в
//     заголовок `Content-Disposition` и разорвут его;
//   · 🪤 зарезервированные имена Windows (`nul`, `con`, `prn`, `aux`, `com1…9`, `lpt1…9`),
//     в том числе с расширением (`nul.md`). Это не теория: в этом проекте файл с именем
//     `nul` уже ломал работу с git. На ноде он не выстрелит (файлы лежат под номером), но
//     имя уедет в браузер владельца и в его папку загрузок, а он на Windows. Замер на этой
//     машине (Win 11 Pro 26200): в устройство уходит только ЧИСТОЕ `nul`, а `nul.md`
//     создаётся обычным файлом — оставляем и его, цена вопроса один подчёрк в имени;
//   · 🪤 СИМВОЛЫ НАПРАВЛЕНИЯ ПИСЬМА (класс `Cf`, например U+202E) вырезаются обязательно:
//     именно ими подменяется ВИДИМОЕ имя файла — на экране одно, на диске другое. Chromium
//     вырезает их у себя не случайно;
//   · имена с точки (`.env`) и двойные расширения (`skill.md.txt`) оставлены КАК ЕСТЬ:
//     скрывать их — значит врать про то, что человек отправил, а вреда на нашей стороне от
//     них нет (файл отдаётся байтами и не исполняется нигде).
const WIN_RESERVED = /^(con|prn|aux|nul|com[1-9]|lpt[1-9])(\.|$)/i;
function attName(v, extHint) {
    let t = String(v == null ? '' : v).replace(/[\u0000-\u001F\u007F]/g, '')
        .replace(/\p{Cf}/gu, '')
        .replace(/[\\/]+/g, '_').replace(/[";]/g, '_').trim();
    // Точки по краям: `..` целиком, ведущее `./`, хвостовая точка (Windows её съедает).
    t = t.replace(/^\.+$/, '').replace(/\.+$/, '');
    if (WIN_RESERVED.test(t)) t = '_' + t;
    if (t.length > MAX_ATT_NAME) {
        // Режем ОСНОВУ, а не хвост: расширение важнее середины имени.
        const dot = t.lastIndexOf('.');
        const ext = dot > 0 ? t.slice(dot, dot + 9) : '';
        t = t.slice(0, MAX_ATT_NAME - ext.length) + ext;
    }
    if (!t) t = 'file.' + (attExtOk(extHint) ? extHint : 'bin');
    return t;
}
// Расширение для хранения: из имени, иначе из подсказки клиента, иначе `bin`. В путь идёт
// только то, что прошло `attExtOk`, то есть строго [a-z0-9]{1,8}.
function attExtOf(name, hint) {
    const dot = name.lastIndexOf('.');
    const fromName = dot > 0 ? name.slice(dot + 1).toLowerCase().replace(/[^a-z0-9]/g, '').slice(0, 8) : '';
    if (attExtOk(fromName)) return fromName;
    return attExtOk(hint) ? hint : 'bin';
}

// Текст чистим и режем здесь же. Управляющие символы выкидываем не из вкусовщины:
// они уезжают в лог ноды и в вёрстку дашборда. CRLF сводим к LF, иначе лишний CR
// всплывает в UI лишней пустой строкой.
function textClean(v) {
    let t = String(v == null ? '' : v).replace(/\r\n?/g, '\n')
        .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/g, '').trim();
    if (t.length > MAX_TEXT) t = t.slice(0, MAX_TEXT);
    // Обрезка ровно по 2000 может разрубить пару сурогатов (эмодзи) пополам —
    // одинокий хвост убираем, иначе клиент покажет на его месте «□».
    if (/[\uD800-\uDBFF]$/.test(t)) t = t.slice(0, -1);
    return t;
}

// Аватарка: отдельной ручки для неё нет, приезжает полем среза. Предел мерится в
// ДЕКОДИРОВАННЫХ байтах — 20 КБ. Раньше здесь сравнивалась длина строки data-URL, и
// это была не та единица: base64 раздувает данные на треть, поэтому фактический
// потолок оказывался ~15 КБ байт, а хаб честно принимал 20 КБ и клал себе. Наружу
// это выглядело как «у себя лицо видно, у соседей нет», и поймать такое можно было
// только сквозняком. На диске и в трафике лежат байты, значит и мерить их.
// Возвращаем СВОЮ пересобранную строку с честным mime: заявленному `data:image/png`
// верить нельзя, а байты мы уже проверили.
function avatarClean(v) {
    if (typeof v !== 'string' || !v || v.length > MAX_AVATAR_URL) return '';
    const m = /^data:[a-z0-9.+/*-]*;base64,([A-Za-z0-9+/=\s]+)$/i.exec(v);
    if (!m) return '';
    let buf;
    try { buf = Buffer.from(m[1], 'base64'); } catch { return ''; }
    if (buf.length > MAX_AVATAR || !isWebp(buf)) return '';
    return 'data:image/webp;base64,' + buf.toString('base64');
}

// ── Раскладка чата: одна функция на все пути ─────────────────────────────────
// 🔴 `gid === null` — наследуемая плоская раскладка (`chat.ndjson`, `att/<seq>.<ext>`),
// строка из 32 hex — раскладка по группам (`chat/<gid>.ndjson`, `att/<gid>/<seq>.<ext>`).
// Собирается путь ТОЛЬКО здесь: вторая сборка того же пути и была тем баком, из которого
// файл уже никто не удалит — `chatDropAtt` строил имя своей строкой `${seq}.webp`, и с
// приходом второго расширения сообщение уходило из журнала, а байты оставались на ноде
// навсегда. В путь попадают ровно два своих значения: число `seq` и `gid`, прошедший
// `GID_RE`; присланная строка сюда не доходит по построению.
function chatPaths(gid) {
    if (!gid) {
        return { gid: null, log: CHAT_FILE, seq: SEQ_FILE, tombs: GONE_FILE,
            dirs: { image: ATT_DIR, audio: VOICE_DIR, file: FILE_DIR } };
    }
    if (!GID_RE.test(gid)) throw new Error('gid не прошёл проверку — путь не собирается');
    return { gid, log: path.join(CHAT_DIR, gid + '.ndjson'), seq: path.join(CHAT_DIR, gid + '.seq'),
        tombs: path.join(CHAT_DIR, gid + '.tombs.json'),
        dirs: { image: path.join(ATT_DIR, gid), audio: path.join(VOICE_DIR, gid),
            file: path.join(FILE_DIR, gid) } };
}
const attFile = (p, seq, ext) => {
    const e = attExtOk(ext) ? ext : 'webp';
    return path.join(p.dirs[attType(e).kind] || p.dirs.image, String(Number(seq)) + '.' + e);
};

// Расширение вложения по записи журнала. Записи прежних сборок поля `ext` не знают —
// у них вложение всегда было webp, и это ровно тот файл, который лежит на ноде сейчас.
const attExt = rec => {
    const e = rec && rec.att && rec.att.ext;
    return attExtOk(e) ? e : 'webp';
};
// Длительность звука — ПОДСКАЗКА ОТПРАВИТЕЛЯ в СЕКУНДАХ, и проверить её приёмнику нечем
// (см. разбор у MAX_ATT_AUDIO). Поэтому: диапазон обрезаем, в расчёты не берём, при негодном
// значении поля просто нет — плеер тогда покажет длительность сам, дослушав файл. Верхняя
// граница щедрая (20 минут): врать в меньшую сторону смысла нет, а в большую всё равно
// упрётся в вес.
const attDur = v => {
    const n = Math.round(Number(v));
    return Number.isFinite(n) && n >= 1 && n <= 20 * 60 ? n : null;
};

// ── Белый список полей среза ────────────────────────────────────────────────
// Раньше здесь стоял `{ ...s }`: приёмник проверял три поля, а остальное клал на
// диск дословно и отдавал соседям в `/peers` как нашу правду — в `tot.streak`
// уезжала произвольная строка и попадала в разметку дашборда. Теперь собирается
// НОВЫЙ объект из известных полей известного вида, а незнакомое не хранится вообще:
// приёмник — единственная граница, и «пропустить неизвестное» на ней неправильно
// по определению. Цена — прозрачность реле: новое поле среза надо явно добавить
// сюда, иначе оно до соседей не доедет. Это намеренно.
const WINDOWS = ['h24', 'd7', 'd30', 'all'];
// Точек в ряду. 1500 — это ~4 года суток в окне «всё время» (оно растёт на точку в
// день), то есть честную историю обрезка не тронет. Заявленные в ревизии 400 через
// год начали бы молча резать настоящие данные. Сверху ряд всё равно ограничен телом
// в 64 КБ: шесть рядов по 1500 чисел в него уже не влезут.
const SERIES_MAX = 1500;
const TOT_KEYS_MAX = 64;             // в живом `tot` их 26, запас на рост

// Строка: без управляющих символов (они уезжают в лог и в вёрстку) и по длине.
const strAt = (v, max) => typeof v === 'string'
    ? v.replace(/[\u0000-\u001F\u007F]/g, '').slice(0, max) : '';
// Число: только конечное. Не число — поля просто нет: нуль вместо цифры это тоже
// вранье, а отсутствие потребители уже читают как ноль (`Number(x) || 0`).
const numOr = v => { const n = Number(v); return Number.isFinite(n) ? n : null; };
const numCell = v => { const n = Number(v); return Number.isFinite(n) ? n : 0; };
// `keys` — это ПОДПИСИ (даты и часы), и приводить их к числу нельзя: дашборд
// совмещает ряды соседей ПО КЛЮЧАМ, а не по индексу (у каждой установки своя дата
// первого дня), и числа сломали бы совмещение начисто.
const keyCell = v => strAt(v, 32);
function windowsOf(v, cell) {
    if (!v || typeof v !== 'object' || Array.isArray(v)) return null;
    const out = {};
    for (const w of WINDOWS) {
        // Обрезаем ХВОСТ, а не начало: свежие точки важнее, и одно правило для
        // подписей и значений сохраняет их выравнивание по длине.
        if (Array.isArray(v[w])) out[w] = v[w].slice(-SERIES_MAX).map(cell);
    }
    return Object.keys(out).length ? out : null;
}
// В `tot` строк быть не должно вообще: это счётчики. Любая строка здесь — либо
// ошибка отправителя, либо попытка протащить разметку. Одно негодное поле не
// отменяет срез: выбрасываем поле, цифры принимаем.
function totClean(v) {
    const out = {};
    if (!v || typeof v !== 'object') return out;
    for (const [k, val] of Object.entries(v)) {
        if (Object.keys(out).length >= TOT_KEYS_MAX) break;
        if (!/^\w{1,24}$/.test(k)) continue;
        const n = numOr(val);
        if (n !== null) out[k] = n;
    }
    return out;
}
// Собрать срез заново. Всё, чего здесь нет, на диск не попадает — в том числе
// `stamp` (время ставит сервер) и `src`: это диагностика сшивки САМОГО отправителя,
// её никто у соседа не читает, а полезное в ней — строки, то есть ровно то, чему
// нельзя пересекать границу. Понадобится — добавлять сюда явными полями.
function sliceClean(s, nick, recvAt) {
    const out = { installId: s.installId, nick, recvAt };
    const ver = strAt(s.ver, 32).replace(/[^\w.\-+]/g, '');
    if (ver) out.ver = ver;
    const sha = strAt(s.sha, 64).replace(/[^\w.\-+]/g, '');
    if (sha) out.sha = sha;
    const avatar = avatarClean(s.avatar);
    if (avatar) out.avatar = avatar;
    const tz = numOr(s.tzOffsetMin);
    if (tz !== null) out.tzOffsetMin = Math.trunc(tz);
    const keys = windowsOf(s.keys, keyCell);
    if (keys) out.keys = keys;
    for (const f of ['tok', 'sp', 'tu', 'act', 'acc']) {
        const w = windowsOf(s[f], numCell);
        if (w) out[f] = w;
    }
    out.tot = totClean(s.tot);
    return out;
}

// ── Состояние одного журнала ─────────────────────────────────────────────────
// Раньше журнал, счётчик номеров и надгробия были ТРЕМЯ ГЛОБАЛЬНЫМИ переменными на весь
// процесс. С журналом на группу так нельзя: `lastSeq` одной группы выдавал бы номера
// другой, а один слот кеша означал бы, что две читаемые по очереди группы выбивают друг
// друга — ответы верные, ошибок нет, только каждый опрос заново разбирает файл целиком.
// Поэтому состояние собрано в один объект на группу, и всё, что работает с журналом,
// принимает его первым аргументом. Наследуемая плоская раскладка — это тот же объект с
// `gid === null`, то есть ОДИН путь в коде, а не второй.
const CTX = new Map();
let readTick = 0;
function ctxOf(gid) {
    const k = gid || '';
    let c = CTX.get(k);
    if (c) return c;
    c = { p: chatPaths(gid || null), cache: { key: '', list: [] }, read: 0,
        lastSeq: null, gone: null, gseq: 0, cut: 0 };
    CTX.set(k, c);
    return c;
}
// Журнал читаем с диска, но кэшируем по (mtime, size): GET /chat дёргают часто, а
// разбирать 1000 строк на каждый опрос незачем. Кэш по метке файла, а не «прочитали
// один раз при старте» — иначе внешняя правка или чистка журнала останутся невидимы.
function chatAll(c) {
    let st;
    try { st = fs.statSync(c.p.log); } catch { c.cache = { key: '', list: [] }; return []; }
    const key = st.mtimeMs + ':' + st.size;
    c.read = ++readTick;
    if (c.cache.key === key) return c.cache.list;
    let raw = '';
    try { raw = fs.readFileSync(c.p.log, 'utf8'); } catch { return []; }
    const list = [];
    for (const line of raw.split('\n')) {
        if (!line.trim()) continue;
        let m;
        // Битая или усечённая строка (падение посреди записи, ручная правка) не
        // имеет права уронить выдачу: пропускаем её, остальные отдаём.
        try { m = JSON.parse(line); } catch { continue; }
        if (m && typeof m === 'object' && Number.isInteger(m.seq)) list.push(m);
    }
    list.sort((a, b) => a.seq - b.seq);
    c.cache = { key, list };
    cacheTrim();
    return list;
}
// Слотов кеша ограниченное число: 50 групп по 1000 строк — это уже десятки мегабайт,
// которые никто не освободит. Выбрасываем РАЗОБРАННЫЙ СПИСОК самого давно читанного, а
// не сам контекст: в контексте живут счётчик номеров и надгробия, и терять их нельзя.
function cacheTrim() {
    const warm = [...CTX.values()].filter(x => x.cache.list.length);
    if (warm.length <= CHAT_CACHE_SLOTS) return;
    warm.sort((a, b) => a.read - b.read);
    for (const x of warm.slice(0, warm.length - CHAT_CACHE_SLOTS)) x.cache = { key: '', list: [] };
}

// ── Надгробия: как удаление доезжает до соседей ──────────────────────────────
// Протокол чтения умел только «добавилось»: клиент просит «новее номера N», получает
// сообщения с номером больше N и дописывает их в конец. Значит удалённое сообщение
// оставалось видимым у ВСЕХ, кроме того, кто его удалил (он перечитывает ленту сам), и
// висело так до полной перезагрузки страницы — то есть кнопка удаления не работала для
// остальных пятерых вообще.
// Поэтому на каждое РЕШЕНИЕ ЧЕЛОВЕКА убрать сообщение пишется надгробие. Клиент получает
// их полем `gone` и убирает у себя эти номера.
//
// 🪤 Курсор надгробий — СВОЙ монотонный счётчик `gseq`, а не время и не номер сообщения,
// и это не украшение:
//   · по времени фильтровать нельзя — ход часов назад (а он бывает) спрятал бы надгробие
//     навсегда;
//   · по номеру сообщения нельзя тем более — удалённый номер по определению НИЖЕ курсора
//     клиента, то есть «отдай новее курсора» не отдало бы ничего.
// Клиент присылает свой `gseq`, приёмник отдаёт надгробия с большим. Догнавший получает
// пустой список и ничего не перечитывает.
//
// Обрезка журнала по лимиту надгробий НЕ ставит. Она снимает 1000 сообщений непрерывным
// низом, и надгробия на них вытеснили бы настоящие удаления из окна, загоняя клиентов в
// постоянное полное перечитывание. Обрезка описывается ОДНИМ числом — `firstSeq` в ответе:
// самое старое сообщение, которое ещё есть. Всё ниже клиент выбрасывает у себя сам.
//
// Файл, а не память: перезапуск сервиса (в том числе после продления сертификата) не
// имеет права воскресить удалённое у всех соседей разом. `cut` — самый большой `gseq`,
// который мы УЖЕ ЗАБЫЛИ (истёк или вытеснен потолком): ниже него полноту не гарантируем,
// и такому клиенту отвечаем `cold`, а не пустым списком. Пустой список читается как
// «ничего не пропало» — это ровно то вранье, от которого весь механизм и заведён.
// Курсоры у каждой группы СВОИ и живут в её же файле надгробий: общий счётчик означал бы,
// что удаление в чужой группе двигает твой курсор и гонит тебя в перечитывание.
function tombsLoad(c) {
    if (c.gone) return c;
    c.gone = []; c.gseq = 0; c.cut = 0;
    try {
        const raw = JSON.parse(fs.readFileSync(c.p.tombs, 'utf8'));
        // Форма файла согласована со скриптом перехода на групповую раскладку
        // (`tools/league-migrate.js`): `{ v, gseq, cut, tombs: [{ seq, at, why, gseq }] }`.
        // Ключ `gone` читается тоже — так файл назывался в первой версии этой правки, и
        // переезд с него не должен требовать ручной работы на ноде.
        const list = Array.isArray(raw) ? raw
            : (raw && Array.isArray(raw.tombs) ? raw.tombs
                : (raw && Array.isArray(raw.gone) ? raw.gone : []));
        c.gone = list.filter(x => x && Number.isInteger(x.seq) && Number.isInteger(x.gseq)
            && Number.isFinite(Date.parse(x.at))).sort((a, b) => a.gseq - b.gseq);
        c.gseq = Math.max(Number((raw || {}).gseq) || 0, ...c.gone.map(g => g.gseq), 0);
        c.cut = Math.max(Number((raw || {}).cut) || 0, 0);
    } catch { /* первого удаления ещё не было */ }
    return c;
}
function goneSave(c) {
    try {
        const tmp = c.p.tombs + '.tmp';
        fs.mkdirSync(path.dirname(c.p.tombs), { recursive: true });
        fs.writeFileSync(tmp, JSON.stringify({ v: 2, gseq: c.gseq, cut: c.cut, tombs: c.gone }));
        fs.renameSync(tmp, c.p.tombs);
        return true;
    } catch (e) { log(`${c.p.tombs} не записался: ${e.message}`); return false; }
}
// Просроченные убираем на чтении, а не по таймеру: чтений и так немного, а таймер — это
// второй планировщик, который надо не забыть завести, не уронить и не запустить дважды.
// Всё забытое поднимает `cut`: забыть тихо — значит соврать клиенту пустым списком.
function goneDrop(c, now) {
    tombsLoad(c);
    const keep = [], lost = [];
    for (const g of c.gone) (now - Date.parse(g.at) < GONE_TTL_MS ? keep : lost).push(g);
    let list = keep;
    if (list.length > GONE_KEEP) {
        lost.push(...list.slice(0, list.length - GONE_KEEP));
        list = list.slice(-GONE_KEEP);
    }
    if (!lost.length) return false;
    for (const g of lost) if (g.gseq > c.cut) c.cut = g.gseq;
    c.gone = list;
    log(`надгробий забыто: ${lost.length} (срок ${Math.round(GONE_TTL_MS / 864e5)} суток`
        + ` или потолок ${GONE_KEEP}), курсор полноты теперь ${c.cut}`
        + (c.p.gid ? ` в группе ${c.p.gid.slice(0, 8)}` : ''));
    return true;
}
function gonePrune(c, now) {
    if (goneDrop(c, now)) goneSave(c);
    return c.gone;
}
// Возвращает { added, saved }: записалось ли надгробие, знать ОБЯЗАТЕЛЬНО. Молчание тут
// значит «удаление состоялось, а соседи о нём не узнают никогда» — отсюда `tombs` в ответе.
function goneAdd(c, seqs, why) {
    tombsLoad(c);
    const at = new Date().toISOString();
    const have = new Set(c.gone.map(g => g.seq));
    let added = 0;
    for (const s of seqs) {
        if (!Number.isInteger(s) || s <= 0 || have.has(s)) continue;
        c.gseq += 1;
        c.gone.push({ seq: s, at, gseq: c.gseq, why });
        have.add(s);
        added++;
    }
    if (!added) return { added: 0, saved: true };
    goneDrop(c, Date.parse(at));
    return { added, saved: goneSave(c) };
}


// Удаление сообщений. Инструментом, из которого нельзя убрать написанное, управлять
// нельзя — а до 05.09 удалить можно было только правкой файла на ноде по SSH.
// Про «права» — см. разбор в handleChatDelete: в наследуемом режиме их нет и быть не
// может, в режиме личности они опираются на ЗАПИСЬ участника, а не на присланные поля.
// Вложение уходит вместе со строкой: файл без сообщения никому не нужен.
// 🔴 Запись журнала обязана отдавать ОТКАЗ, а не ронять процесс. Раньше здесь стоял голый
// `writeFileSync`: при ENOSPC исключение уходило из обработчика запроса наверх, а
// обработчика `uncaughtException` в файле нет — то есть кончившееся место на ноде убивало
// и чат, и обмен срезами у всех шестерых. Чужая переписка при этом не терялась (tmp+rename
// оставляет журнал целым), но сервис падал вместо того, чтобы честно сказать «не могу».
// Возвращает true/false; всё, что пишет журнал, ОБЯЗАНО смотреть на результат.
function chatWriteAll(c, list) {
    const tmp = c.p.log + '.tmp';
    try {
        fs.mkdirSync(path.dirname(c.p.log), { recursive: true });
        fs.writeFileSync(tmp, list.length ? list.map(m => JSON.stringify(m)).join('\n') + '\n' : '');
        fs.renameSync(tmp, c.p.log);
    } catch (e) {
        log(`ЖУРНАЛ ЧАТА НЕ ЗАПИСАЛСЯ: ${e.message} (${e.code || 'без кода'})`);
        try { fs.unlinkSync(tmp); } catch { /* и времянки нет — тем лучше */ }
        return false;
    }
    try {
        const st = fs.statSync(c.p.log);
        c.cache = { key: st.mtimeMs + ':' + st.size, list };
        c.read = ++readTick;
    } catch { c.cache = { key: '', list: [] }; }
    return true;
}
function chatDropAtt(c, rec) {
    if (!rec || !rec.att) return;
    // Имя — через общую функцию, а не своей строкой. Отдельная сборка пути здесь и была
    // тем баком, из которого файл уже никто не удалит: строка уходит из журнала, ссылку
    // никто не отдаст, а байты лежат на ноде до ручной чистки.
    try { fs.unlinkSync(attFile(c.p, rec.seq, attExt(rec))); } catch { /* уже нет — не беда */ }
}
// Снимок журнала ПЕРЕД массовым удалением. Это переписка шести живых людей, а `all=1`
// необратим: до снимка единственным способом вернуть снесённое был бэкап всей ноды.
// Копируем только текст: вложения уходят вместе со строками, тащить за ними мегабайты
// картинок ради отката незачем, а 1000 строк — это ~150 КБ. Снимков держим последние
// CHAT_BAK_KEEP, иначе «страховка» сама съест диск, за который мы тут воюем.
// 🪤 Кап держится на СВОЁМ наборе: у плоской раскладки имя `chat-<штамп>.bak.ndjson`, у
// группы — `chat-<gid8>-<штамп>.bak.ndjson`. Один общий кап на все группы означал бы, что
// шесть чисток в болтливой группе выметают единственный снимок тихой.
function chatBackup(c) {
    let raw;
    try { raw = fs.readFileSync(c.p.log); } catch { return null; }
    if (!raw.length) return null;
    // Штамп с миллисекундами: `mine=1` и `all=1` подряд укладываются в одну секунду, и
    // снимок без миллисекунд затёр бы более полный предыдущий.
    const tag = c.p.gid ? c.p.gid.slice(0, 8) + '-' : '';
    const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 23);
    const name = `chat-${tag}${stamp}.bak.ndjson`;
    const mine = c.p.gid
        ? new RegExp('^chat-' + c.p.gid.slice(0, 8) + '-.+\\.bak\\.ndjson$')
        : /^chat-\d{4}-.+\.bak\.ndjson$/;
    try { fs.writeFileSync(path.join(DATA, name), raw); }
    catch (e) { log(`снимок журнала не записался: ${e.message}`); return null; }
    try {
        const old = fs.readdirSync(DATA).filter(f => mine.test(f)).sort();
        for (const f of old.slice(0, Math.max(0, old.length - CHAT_BAK_KEEP))) {
            fs.unlinkSync(path.join(DATA, f));
        }
    } catch { /* не вышло подмести — снимок всё равно на месте */ }
    log(`снимок журнала перед массовым удалением: ${name}, ${raw.length} Б`);
    return name;
}
// Наследуемый режим:
//   DELETE /chat/<seq>?installId=…[&force=1] — одно сообщение.
//   DELETE /chat?installId=…                — все сообщения установки.
//   DELETE /chat?all=1                      — весь журнал (та же ограда, что и force).
// Режим личности (везде обязателен `gid`, и он обязан быть в записи спрашивающего):
//   DELETE /chat/<seq>?gid=G[&force=1] — своё; чужое — только СОЗДАТЕЛЬ группы и только
//                                        с `force=1`.
//   DELETE /chat?gid=G&mine=1          — все свои в этой группе.
//   DELETE /chat?gid=G&all=1           — весь журнал группы; только СОЗДАТЕЛЬ.
// 🔴 `?installId=` в режиме личности не читается ВООБЩЕ — ни как цель, ни как сверка.
// Как цель это была бы раздача чужих сообщений по строке запроса, а как сверка — тупик
// 05.09: она ломает живую кнопку «убрать мои» и при этом ничего не проверяет. Поэтому
// старая форма `?installId=<свой>` от хаба продолжает работать и означает «мои»,
// независимо от присланного значения.
function handleChatDelete(req, res, u, me) {
    // Ограничение частоты: на сообщение — 20 в минуту, на срез — один, а на самой
    // разрушительной ручке не было НИЧЕГО. Считаем и отказы: каждый запрос всё равно
    // читает журнал, а массовый — ещё и переписывает его со снимком.
    // Ведро в режиме личности — на УЧАСТНИКА: общее ведро означало бы, что один
    // чистящий журнал циклом отбирает квоту у остальных пятерых.
    const bucket = me ? 'delete:' + me.memberId : 'delete';
    if (!rateOk(keyRate, bucket, DELETE_PER_MIN)) {
        return json(res, 429, { error: `не больше ${DELETE_PER_MIN} удалений в минуту `
                + (me ? 'на участника' : 'на ключ'),
            retryAfterMs: 60_000,
            hint: 'подожди минуту; чистить журнал пачкой дешевле одним запросом'
                + (me ? ' (?mine=1 или ?all=1)' : ' (?installId=<свой> или ?all=1)')
                + ', чем перебором сообщений' });
    }
    const force = u.searchParams.get('force') === '1';
    const all = u.searchParams.get('all') === '1';
    const mine = u.searchParams.get('mine') === '1';
    const who = String(u.searchParams.get('installId') || '');
    const m = /^\/chat\/(\d{1,15})$/.exec(u.pathname);
    let c, why;
    if (me) {
        const gid = String(u.searchParams.get('gid') || '');
        if (!GID_RE.test(gid)) {
            return json(res, 400, { error: 'нужен gid=<группа>: смысл «весь журнал» без группы'
                    + ' не определён, а угадывать её приёмник не станет',
                hint: 'список своих групп — GET /me' });
        }
        if (!inGroup(me, gid)) return json(res, 403, { error: 'ты не в этой группе' });
        c = ctxOf(gid);
        // `all=1` необратим и бьёт по переписке всех членов группы, поэтому это право
        // создателя, а не «любого с токеном». Асимметрия та же, что у исключения:
        // право, за которым нет отката, не выдаётся всем.
        if (all && !isCreator(me, gid)) {
            return json(res, 403, { error: 'снести журнал группы целиком может только её создатель',
                hint: 'свои сообщения убираются без оговорок: ?mine=1' });
        }
    } else {
        c = ctxOf(null);
    }
    const list = chatAll(c);
    let doomed;
    if (m) {
        const seq = Number(m[1]);
        const rec = list.find(x => x.seq === seq);
        if (!rec) return json(res, 404, { error: 'нет такого сообщения' });
        if (me) {
            // 🔴 «Своё» определяется `installId` ИЗ ЗАПИСИ участника, а не из строки
            // запроса. Это и есть разница с тупиком 05.09: тогда сверялись две величины,
            // присланные одним и тем же звонящим, — то есть не проверялось ничего.
            const own = !!me.installId && rec.installId === me.installId;
            if (!own && !isCreator(me, c.p.gid)) {
                return json(res, 403, { error: 'это чужое сообщение: снести его может автор'
                        + ' или создатель группы' });
            }
            if (!own && !force) {
                return json(res, 403, { error: 'чужое сообщение сносится только с force=1',
                    hint: 'осознанность нужна и создателю группы: автор об этом не узнает' });
            }
        } else if (!force && rec.installId !== who) {
            return json(res, 403, { error: 'это чужое сообщение; своё удаляется без оговорок, чужое — только force=1' });
        }
        doomed = [rec];
    } else if (all) {
        doomed = list.slice();
    } else if (me) {
        if (!me.installId) {
            return json(res, 409, { error: 'установка ещё не привязана к твоей записи —'
                    + ' удалять по себе нечего', hint: 'привязка появится с первым срезом' });
        }
        doomed = list.filter(x => x.installId === me.installId);
        why = 'mine';
    } else if (idOk(who)) {
        // ⚠️ Проверки владения здесь БЫТЬ НЕ МОЖЕТ, пока ключ один на всех, и её тут
        // пробовали 05.09 — откатили в тот же час. В наследуемом режиме приёмник физически
        // не знает, кто к нему обратился: единственный признак личности — общий секрет,
        // одинаковый у шестерых. Любая проверка «этот installId твой или чужой» опирается
        // либо на данные, которые присылает сам запросивший, либо на адрес, который у
        // честного хаба меняется, — то есть не проверяет ничего, зато ломает живую кнопку
        // «убрать мои» (хаб отправляет ровно `/chat?installId=<свой>` и получал бы 403).
        // Настоящая ограда появляется ВЫШЕ, в режиме личности, и опирается на запись.
        // Что защищает здесь: ограничение частоты выше, снимок журнала ниже и видимое
        // событие в логе. Настоящая угроза — промах и лавина, а не шпион.
        doomed = list.filter(x => x.installId === who);
    } else {
        return json(res, 400, { error: 'нужен installId, либо all=1, либо /chat/<seq>' });
    }
    if (!doomed.length) return json(res, 200, { ok: true, removed: 0, left: list.length, tombs: true });
    if (!m) chatBackup(c);
    const kill = new Set(doomed.map(x => x.seq));
    const left = list.filter(x => !kill.has(x.seq));
    // Порядок: СНАЧАЛА журнал, потом надгробие. Наоборот — это надгробие на сообщение,
    // которое осталось на месте, то есть строка, исчезнувшая у соседей и живая здесь.
    if (!chatWriteAll(c, left)) {
        return json(res, 507, { error: 'журнал не записался — удаление не выполнено',
            hint: 'скорее всего на ноде кончилось место; переписка при этом цела,'
                + ' журнал переписывается через времянку' });
    }
    for (const rec of doomed) chatDropAtt(c, rec);
    // Надгробия — на ВСЕХ путях удаления, и результат записи возвращается наружу: если
    // надгробие не легло, удаление СОСТОЯЛОСЬ, а соседи о нём не узнают никогда. Молчать
    // об этом нельзя, поэтому `tombs: false` — часть ответа, а не строчка в логе.
    const marks = goneAdd(c, [...kill], m ? 'one' : (all ? 'all' : (why || 'mine')));
    log(`удалено сообщений: ${doomed.length}, осталось ${left.length}, надгробий +${marks.added}`
        + `${marks.saved ? '' : ' (НЕ ЗАПИСАНЫ)'}`
        + (c.p.gid ? ` в группе ${c.p.gid.slice(0, 8)}` : '')
        + ` (с ${addrOf(req) || 'неизвестного адреса'}${force ? ', force=1' : ''})`);
    return json(res, 200, { ok: true, removed: doomed.length, left: left.length,
        seqs: doomed.map(x => x.seq), tombs: marks.saved,
        ...(c.p.gid ? { gid: c.p.gid } : {}),
        ...(marks.saved ? {} : { warn: 'надгробия не записались: у соседей сообщение'
            + ' останется на экране до полного перечитывания ленты' }) });
}

// Пишем целиком через tmp+rename, как и срезы: так в журнале физически не может
// появиться обрезанная строка от нашего же падения, а обрезка до 1000 достаётся
// бесплатно. Цена — перезапись файла на каждое сообщение, но это 1000 коротких
// строк (~150 КБ), а чат — на горстку человек, не шина сообщений.
// Обрезка — 1000 НА ГРУППУ, а не на приёмник: общее окно означало бы, что болтливая
// группа вытесняет историю тихой, и никто ничего для этого не делал.
function chatAppend(c, rec) {
    const was = chatAll(c);
    const keep = was.concat([rec]).slice(-CHAT_KEEP);
    // Обрезка снимает и ВЛОЖЕНИЯ выпавших сообщений. Раньше их не удалял никто: строка
    // уходила из журнала, ссылку на файл больше никто не отдаст, а место он занимал до
    // ручной чистки. Выпадают всегда с НАЧАЛА — обрезка берёт хвост.
    const dropped = was.length + 1 - keep.length;
    // Надгробий обрезка НЕ ставит: 1000 надгробий непрерывным низом вытеснили бы настоящие
    // удаления из окна и загнали клиентов в постоянное полное перечитывание. Обрезка
    // описывается одним числом — `firstSeq` в ответе на чтение.
    // Порядок важен: сначала пишем журнал, и только на успехе снимаем вложения. Наоборот
    // — это удалённые файлы у сообщений, которые остались в журнале.
    if (!chatWriteAll(c, keep)) return false;
    for (let i = 0; i < dropped; i++) chatDropAtt(c, was[i]);
    return true;
}

// Счётчик seq лежит в файле и НЕ сбрасывается при перезапуске: клиент по seq
// решает, что для него новое. Выданный второй раз номер показал бы старые
// сообщения как новые, а откат счётчика — спрятал бы новые навсегда.
// Отсюда же следствие: двух приёмников на один каталог данных быть не должно —
// каждый ведёт свой `lastSeq` в памяти, и номера разъедутся. Юнит один.
// 🔴 Счётчик СВОЙ у каждой группы и восстанавливается по ЕЁ журналу. Раньше это была
// одна переменная и один журнал; с несколькими журналами глобальный счётчик
// восстановился бы НИЖЕ фактического максимума и начал выдавать номера по второму кругу —
// а повторный номер не ломает ручку, он тихо прячет сообщения у всех клиентов.
function seqInit(c) {
    if (c.lastSeq !== null) return c.lastSeq;
    let fromFile = 0;
    try { fromFile = parseInt(fs.readFileSync(c.p.seq, 'utf8').trim(), 10) || 0; } catch { /* первый запуск */ }
    // Файл счётчика мог потеряться (перенос каталога, чистка) — тогда берём максимум
    // из журнала. Именно максимум из двух: журнал обрезается до 1000, и его
    // последний seq бывает меньше уже выданного.
    let fromLog = 0;
    for (const m of chatAll(c)) if (m.seq > fromLog) fromLog = m.seq;
    c.lastSeq = Math.max(fromFile, fromLog, 0);
    return c.lastSeq;
}
// Выдача синхронная от начала до конца: Node не переключит нас посреди этой
// функции, поэтому два одновременных POST физически не могут получить один номер.
// 🔴 Если номер не записался (кончилось место), откатываем счётчик и возвращаем 0: выдать
// номер, которого не будет в файле, — значит после перезапуска выдать его ВТОРОЙ РАЗ, а
// повторный seq не ломает ручку, он тихо прячет сообщения у всех клиентов. Отказ здесь
// честнее падения: раньше исключение из этой функции убивало процесс целиком.
function nextSeq(c) {
    const want = seqInit(c) + 1;
    const tmp = c.p.seq + '.tmp';
    try {
        fs.mkdirSync(path.dirname(c.p.seq), { recursive: true });
        fs.writeFileSync(tmp, String(want) + '\n');
        fs.renameSync(tmp, c.p.seq);
    } catch (e) {
        log(`СЧЁТЧИК СООБЩЕНИЙ НЕ ЗАПИСАЛСЯ: ${e.message} (${e.code || 'без кода'})`);
        try { fs.unlinkSync(tmp); } catch { /* нет и нет */ }
        return 0;
    }
    c.lastSeq = want;
    return c.lastSeq;
}


