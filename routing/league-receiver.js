// ── Серия отказов по просадке ───────────────────────────────────────────────
// Состояние живёт в файле, а не в памяти: перезапуск приёмника не должен обнулять
// счётчик и продлевать заклинивание. Серия привязана к АДРЕСУ: отказы с разных машин в
// одну серию не складываются — «одна установка просела» и «пятеро по разу постучали»
// это разные события. Совпадения с зарегистрированным владельцем НЕ требуем намеренно:
// адрес мог смениться (динамический IP, переезд), а обновляется он только на успешном
// срезе — то есть требование замкнуло бы участника в том самом вечном 409, от которого
// этот механизм и заведён. Вместо запрета — видимость: в событии написано, тот же адрес
// или другой.
const DROPS_FILE = path.join(DATA, 'slice-drops.json');
let drops = {};
try {
    const d = JSON.parse(fs.readFileSync(DROPS_FILE, 'utf8'));
    if (d && typeof d === 'object' && !Array.isArray(d)) drops = d;
} catch { /* первый запуск */ }
function dropsSave() {
    const now = Date.now();
    for (const [k, v] of Object.entries(drops)) {
        if (!v || !(now - v.last < DROP_RESET_MS)) delete drops[k];
    }
    try {
        const tmp = DROPS_FILE + '.tmp';
        fs.writeFileSync(tmp, JSON.stringify(drops), { mode: 0o600 });
        fs.renameSync(tmp, DROPS_FILE);
    } catch (e) { log(`${DROPS_FILE} не записался: ${e.message}`); }
}
function dropProgress(id, req, reason) {
    const now = Date.now();
    const tag = addrTag(addrOf(req));
    let d = drops[id];
    if (!d || d.tag !== tag || now - d.last > DROP_RESET_MS) d = { tag, n: 0, first: now, last: now };
    d.n += 1;
    d.last = now;
    d.reason = reason;
    drops[id] = d;
    dropsSave();
    const spanMs = now - d.first;
    return { n: d.n, spanMs, sameAddr: owners[id] === tag,
        accept: d.n >= DROP_ACCEPT_AFTER && spanMs >= DROP_MIN_SPAN_MS };
}
function dropClear(id) {
    if (!drops[id]) return;
    delete drops[id];
    dropsSave();
}

// Скользящее окно в памяти — один движок на все ограничения (чат, голос, срезы, удаления,
// отдача вложений). Перезапуск окно обнуляет, и это осознанно: счётчик флуда не стоит
// записи в файл на каждый запрос. Ширина окна — параметр: у голосовых она час, а не минута.
function rateOk(map, id, limit, windowMs = 60_000) {
    const now = Date.now();
    const hits = (map.get(id) || []).filter(t => now - t < windowMs);
    if (hits.length >= limit) { map.set(id, hits); return false; }
    hits.push(now);
    map.set(id, hits);
    // Карта не должна расти вечно: раз в сотню ключей выметаем остывшие.
    if (map.size > 200) {
        for (const [k, v] of map) if (!v.some(t => now - t < windowMs)) map.delete(k);
    }
    return true;
}
