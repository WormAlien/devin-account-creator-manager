// Абсолютные потолки правдоподобия. Проверяются у КАЖДОГО среза, а не только начиная
// со второго: `checkMonotone` без предыдущего среза возвращает null, поэтому до этой
// функции новая установка первым же срезом ставила любые конечные числа и садилась на
// вершину рейтинга навсегда — ни одна проверка её не касалась. Возвращает
// строку-причину или null.
function checkAbsolute(s) {
    const t = s.tot || {};
    const pairs = [
        ['tokA', Number(t.tokA) || 0],
        ['promptsAll', Number(t.promptsAll) || 0],
        ['spentAll', Number(t.spentAll) || 0],
        ['acc', (Number(t.bought) || 0) + (Number(t.reg) || 0)],
    ];
    for (const [name, v] of pairs) {
        if (v > ABS_MAX[name]) return `${name}=${v} выше потолка правдоподобия ${ABS_MAX[name]}`;
    }
    for (const [f, cap] of Object.entries(ABS_MAX_SERIES)) {
        const w = s[f];
        if (!w || typeof w !== 'object') continue;
        for (const [win, arr] of Object.entries(w)) {
            let sum = 0, peak = 0;
            for (const n of arr) { sum += n; const a = Math.abs(n); if (a > peak) peak = a; }
            // Точку проверяем и у слагаемых тоже: `[1e300, -1e300]` даёт сумму около
            // нуля, а ось графика у соседа при этом уезжает в бесконечность.
            if (peak > cap) return `${f}.${win}: точка ${peak} выше потолка ${cap}`;
            if (SERIES_LEVEL.has(f)) continue;
            if (Math.abs(sum) > cap) return `${f}.${win}: сумма ${Math.round(sum)} выше потолка ${cap}`;
            // Пара нулевая — либо отправитель старой версии, либо поля просто нет:
            // тогда сходимость не проверяем, потолок выше уже сработал.
            const pair = SERIES_PAIR[f] ? Number(t[SERIES_PAIR[f]]) || 0 : 0;
            if (pair > 0 && sum > pair * SERIES_PAIR_SLACK) {
                return `${f}.${win}: сумма ${Math.round(sum)} не сходится с ${SERIES_PAIR[f]}=${pair}`;
            }
        }
    }
    return null;
}

// Монотонные счётчики: убывать не могут по смыслу. Возвращает строку-причину или null.
function checkMonotone(prev, next) {
    if (!prev) return null;
    // Промежуток — ДРОБНЫЕ часы. Было `Math.max(1, Δч)`, и при сдаче раз в минуту это
    // разрешало прирост на целый часовой потолок КАЖДУЮ минуту: потолок оказывался
    // слабее заявленного в 60 раз. Пол — минимальный законный интервал между срезами
    // (MIN_GAP_MS): чаще честного среза не бывает, а ход часов назад иначе давал бы
    // отрицательный потолок и рубил законный срез. Сверху промежуток НЕ подрезан
    // намеренно — машина могла стоять сутки, и её большой прирост законен; от
    // бесконечного накопления страхуют абсолютные потолки. Битый `recvAt` в прошлом
    // срезе (ручная правка файла) не повод отвергать всё навсегда: тогда проверяем
    // только «не убыло».
    const gapMs = Date.parse(next.recvAt) - Date.parse(prev.recvAt);
    const gap = Number.isFinite(gapMs) ? Math.max(MIN_GAP_MS, gapMs) / 3600000 : null;
    const pt = prev.tot || {}, nt = next.tot || {};
    const pairs = [
        ['tokA', Number(nt.tokA) || 0, Number(pt.tokA) || 0],
        ['promptsAll', Number(nt.promptsAll) || 0, Number(pt.promptsAll) || 0],
        ['spentAll', Number(nt.spentAll) || 0, Number(pt.spentAll) || 0],
        ['acc', (Number(nt.bought) || 0) + (Number(nt.reg) || 0),
                (Number(pt.bought) || 0) + (Number(pt.reg) || 0)],
    ];
    for (const [name, now, was] of pairs) {
        // Небольшой минус прощаем: журнал хаба обрезается по размеру, и «всего» может
        // законно просесть. Обвал же — признак подмены или чужой машины под тем же id.
        if (now < was * 0.9) return `${name} убыл: ${was} → ${now}`;
        if (gap === null) continue;
        const cap = RATE_PER_HOUR[name] * gap;
        if (now - was > cap) return `${name} вырос на ${Math.round(now - was)} за ${gap.toFixed(2)} ч, потолок ${Math.round(cap)}`;
    }
    return null;
}

// В режиме личности `installId` и ник берутся ИЗ ЗАПИСИ участника, а тело в решениях не
// участвует: приёмник перезаписывает их своими, ровно как уже перезаписывает `recvAt` и
// как сам назначает `seq` в чате. Фразу «сверим присланный installId с настоящим» здесь
// негде написать — данных этих в решении больше нет.
// 🪤 Ровно одно исключение, и оно названо в дизайне: запись, созданную приглашением, ещё
// НЕ к чему привязать, и `installId` прибивается ПЕРВЫМ ПРИНЯТЫМ СРЕЗОМ — тем, под
// которым сюда доехал настоящий срез. Дальше он не меняется: другой `installId` под тем
// же токеном получает 409 с внятной причиной, а не заводит вторую строку в рейтинге.
// Окно «участник сам называет себя» этим сжимается до одного запроса — до того самого,
// которым личность и создаётся; переставить привязку может только владелец ноды правкой
// `members.json` (это же и лечение случая «токен цел, а hub-identity.json потерялся»).
// Ник — не решение, а свойство самого себя, поэтому он переезжает в запись: иначе один
// человек показывал бы разные ники в разных сообщениях. Переименование доедет следующим
// тиком, и это названная в дизайне цена.
function sliceIdentity(res, me, s) {
    if (!me) {
        if (!idOk(s.installId)) { json(res, 400, { error: 'installId не похож на наш' }); return null; }
        const nick = nickClean(s.nick);
        if (!nick) { json(res, 400, { error: 'ник от 2 до 20 символов' }); return null; }
        return { installId: s.installId, nick };
    }
    let installId = String(me.installId || '');
    if (!idOk(installId)) {
        if (!idOk(s.installId)) {
            json(res, 400, { error: 'installId не похож на наш: запись участника ещё не'
                    + ' привязана к установке, и привязать её нечем',
                hint: 'первый срез прибивает привязку — пришли свой installId один раз' });
            return null;
        }
        installId = s.installId;
    } else if (idOk(s.installId) && s.installId !== installId) {
        // Отказ, а не молчаливая перезапись: перезаписав, мы приняли бы срез под ДРУГИМ
        // идентификатором, чем думает хаб, и рейтинг молча разошёлся бы с его экраном.
        json(res, 409, { error: 'этот токен привязан к другой установке',
            boundTo: installId.slice(0, 8) + '…', got: String(s.installId).slice(0, 8) + '…',
            hint: 'так выглядит либо потерянный hub-identity.json, либо токен, скопированный'
                + ' на вторую машину. Переставить привязку может только владелец ноды —'
                + ' правкой members.json' });
        return null;
    }
    // Ник: годный из тела обновляет запись (это переименование самого себя), негодный —
    // не повод терять срез, тогда остаётся тот, что уже лежит в записи.
    const want = nickClean(s.nick);
    const nick = want || nickClean(me.nick) || 'mem-' + (String(me.memberId || '0000').slice(0, 4));
    const st = membersState();
    const cur = st.state === 'ok' ? st.map[me.memberId] : null;
    if (cur && (cur.installId !== installId || cur.nick !== nick)) {
        // Пишем КОПИЮ карты, а не правим кеш на месте: неудачная запись оставила бы в
        // памяти состояние, которого нет на диске, и отдавала бы его до следующей правки
        // файла — тихое расхождение вместо честного отказа.
        const map = { ...st.map, [me.memberId]: { ...cur, installId, nick } };
        if (!writeState(MEMBERS_FILE, map, 0o600)) {
            json(res, 507, { error: 'members.json не записался — привязка не сохранена',
                hint: 'на ноде кончилось место или нет прав; срез не принят, чтобы привязка'
                    + ' и рейтинг не разошлись' });
            return null;
        }
        log(`участник ${me.memberId}: установка ${installId.slice(0, 8)}, ник ${nick}`);
    }
    return { installId, nick };
}

function handleSlice(req, res, raw, me) {
    let s;
    try { s = JSON.parse(raw); } catch { return json(res, 400, { error: 'тело не JSON' }); }
    if (!s || typeof s !== 'object') return json(res, 400, { error: 'тело не JSON' });
    if (!s.tot || typeof s.tot !== 'object') return json(res, 400, { error: 'нет tot' });
    const who = sliceIdentity(res, me, s);
    if (!who) return;
    const { installId, nick } = who;
    const prev = readSlice(installId);
    const now = Date.now();
    if (prev && now - Date.parse(prev.recvAt) < MIN_GAP_MS) {
        return json(res, 429, { error: 'один срез в минуту',
            retryAfterMs: MIN_GAP_MS - (now - Date.parse(prev.recvAt)),
            hint: 'ничего делать не надо: хаб сдаёт срез каждые 10 минут сам, дождись следующего тика' });
    }
    // «Один срез в минуту» жило ТОЛЬКО при наличии предыдущего среза, а в наследуемом
    // режиме installId выбирает клиент: цикл со сменой id обходил ограничение целиком.
    // Отсюда второе ведро. В режиме личности оно естественно привязано к УЧАСТНИКУ:
    // общее ведро означало бы, что один сдающий срезы циклом отбирает квоту у остальных.
    if (!rateOk(keyRate, me ? 'slice:' + me.memberId : 'slice', SLICE_PER_MIN)) {
        return json(res, 429, { error: `не больше ${SLICE_PER_MIN} срезов в минуту `
                + (me ? 'на участника' : 'на ключ'),
            retryAfterMs: 60_000,
            hint: (me ? 'квота твоя собственная; ' : 'квота общая на всех держателей ключа; ')
                + 'подожди минуту и сдай снова — если упирается постоянно, срезы сдаются циклом' });
    }
    sliceSweep(false);
    if (!prev) {
        const n = sliceCount();
        // Потолок числа установок остаётся ГЛОБАЛЬНЫМ и в режиме личности: он про диск
        // ноды, а не про человека.
        if (n >= MAX_INSTALLS) {
            log(`ОТКАЗ новой установке ${nick} (${installId.slice(0, 8)}): установок уже ${n}`);
            return json(res, 507, { error: `на ${me ? 'приёмнике' : 'ключе'} уже ${n} установок,`
                    + ' новые не принимаются',
                installs: n,
                hint: `срез-файлы без обновлений ${Math.round(SLICE_TTL_MS / 864e5)} дней приёмник`
                    + ' убирает сам; если установка живая — скажи владельцу ноды, место кончилось' });
        }
    }
    // Собираем срез ЗАНОВО по белому списку: копия присланного объекта означала бы,
    // что любое неизвестное поле уедет соседям как наша правда. Клиентский `stamp`
    // при этом исчезает сам — время ставит сервер, и подделать «свежесть» нечем.
    // Аватарка не имеет права утопить цифры: негодная выбрасывается внутри, а срез
    // принимается. Сообщение важнее лица.
    const next = sliceClean({ ...s, installId }, nick, new Date(now).toISOString());
    // Порядок важен: абсолютные потолки — жёсткий отказ без всяких поблажек, и в серию
    // просадок такой отказ не складывается. Поблажка есть только у ПРОСАДКИ (см.
    // DROP_ACCEPT_AFTER): резкий скачок ВВЕРХ отвергается как раньше и всегда.
    const hard = checkAbsolute(next);
    const bad = hard || checkMonotone(prev, next);
    let rebased = null;
    if (bad) {
        const drop = !hard && / убыл: /.test(bad) ? dropProgress(installId, req, bad) : null;
        if (!drop || !drop.accept) {
            log(`ОТВЕРГНУТ ${nick} (${installId.slice(0, 8)}): ${bad}`
                + (drop ? ` [просадка, отказ ${drop.n} из ${DROP_ACCEPT_AFTER}]` : ''));
            // Что делать дальше — в самом ответе: хаб кладёт первые 160 символов тела в
            // «состояние обмена», и участник видит ровно эту строку, а не журнал ноды.
            const body = drop
                ? { error: `просадка отвергнута, отказ ${drop.n} из ${DROP_ACCEPT_AFTER};`
                        + ' дальше приёмник примет её новой базой сам', reason: bad }
                : { error: 'срез не сходится с прошлым', reason: bad };
            body.hint = drop
                ? 'если числа просели законно (обрезался журнал, переустановка, чистка кеша) —'
                    + ' просто продолжай сдавать срезы, вмешиваться не надо'
                : 'проверь источник цифр: приёмник не принимает ни обвал накопительных'
                    + ' счётчиков, ни рост выше физически возможного';
            if (drop) {
                body.drop = { n: drop.n, need: DROP_ACCEPT_AFTER, spanMs: drop.spanMs,
                    waitMs: Math.max(0, DROP_MIN_SPAN_MS - drop.spanMs) };
            }
            return json(res, 409, body);
        }
        rebased = { at: next.recvAt, reason: bad, afterRejects: drop.n,
            spanMin: Math.round(drop.spanMs / 60000), sameAddr: drop.sameAddr };
        log(`БАЗА ПЕРЕСЧИТАНА ${nick} (${installId.slice(0, 8)}): ${bad};`
            + ` ${drop.n} отказов за ${rebased.spanMin} мин, адрес`
            + ` ${drop.sameAddr ? 'тот же, что у срезов' : 'ДРУГОЙ, чем у срезов этой установки'}`);
    }
    // Серия сброшена: срез принят, заклинивания больше нет.
    dropClear(installId);
    if (rebased) next.rebased = rebased;
    // Событие видно неделю, а не один тик: молчаливая деградация — ровно то, из-за чего
    // весь этот механизм и появился. Уезжает и соседям в /peers, поле серверное.
    else if (prev && prev.rebased && Date.now() - Date.parse(prev.rebased.at) < REBASED_SHOW_MS) {
        next.rebased = prev.rebased;
    }
    const tmp = sliceFile(installId) + '.tmp';
    fs.writeFileSync(tmp, JSON.stringify(next));
    fs.renameSync(tmp, sliceFile(installId));
    // Адрес запоминаем ПОСЛЕ приёма: «свой installId» — это тот, под которым сюда
    // доехал настоящий срез, а не тот, который кто-то назвал в строке запроса.
    ownersRemember(installId, req);
    // Кеш `/health` сбрасываем явно, иначе `installs`/`last` отстанут на TTL, а на них
    // смотрит состояние обмена в дашборде.
    healthCache.at = 0;
    log(`принят ${nick} (${installId.slice(0, 8)}), ${Buffer.byteLength(raw)} Б`);
    json(res, 200, { ok: true, nick, recvAt: next.recvAt, installs: healthBody().installs,
        ...(me ? { memberId: me.memberId, installId } : {}),
        ...(next.rebased ? { rebased: next.rebased } : {}) });
}

// ── Публичная строка рейтинга ────────────────────────────────────────────────
// 🔴 Собирается ОДНОЙ функцией по белому списку, как `sliceClean`: новое поле среза не
// доедет до публичной доски, пока его не впишут сюда явно. Это то свойство, из-за
// которого схема выживет через полгода правок.
// Чего здесь НЕТ и не должно появиться:
//   · `installId` — это ключ, которым сшита вся история машины, и цель для удаления
//     сообщений. Раздав его, мы дарим незнакомцу шаг «перечислить участников»;
//   · `avatar` — лицо живого человека рядом с кривой расхода;
//   · `ver` и `sha` — они говорят, какие уже закрытые дыры на этой установке ещё открыты;
//   · `tzOffsetMin` — грубая геолокация, а ряды совмещаются ПО КЛЮЧАМ, не по времени;
//   · `rebased.sameAddr` — утверждение про сетевую личность участника. Сам факт пересчёта
//     базы остаётся: это антижульническое раскрытие, оно и должно быть видно.
// Всё перечисленное отдаёт `GET /group/<gid>` — только членам группы. Нет группы — нет
// лица, и получить его, не будучи в группе, нечем.
// ⚠️ Ветвления «свой/чужой» внутри публичной ручки нет НАМЕРЕННО: такое ветвление и есть
// забытый фильтр. Форму ответа выбирает РАСКЛАДКА ДАННЫХ (наследуемая или личности), а
// не спрашивающий, и в режиме личности она одна на всех.
const PEER_PUBLIC = ['nick', 'recvAt', 'keys', 'tok', 'sp', 'tu', 'act', 'acc', 'tot'];
function peerPublic(s) {
    const out = { rid: ridOf(s.installId) };
    for (const k of PEER_PUBLIC) if (s[k] !== undefined) out[k] = s[k];
    if (s.rebased && typeof s.rebased === 'object') {
        out.rebased = { at: s.rebased.at, reason: s.rebased.reason,
            afterRejects: s.rebased.afterRejects, spanMin: s.rebased.spanMin };
    }
    return out;
}
function handlePeers(req, res, u, me, identity) {
    const now = Date.now();
    // Своя строка себе не возвращается — фильтр стоит НА СЕРВЕРЕ, и это единственная
    // причина, по которой он работает. В режиме личности «своё» берётся из записи, а
    // параметр строки запроса не читается вовсе: раньше им можно было спрятать соседа
    // от себя, назвавшись его идентификатором.
    const mine = identity ? String((me && me.installId) || '') : (u.searchParams.get('installId') || '');
    const rows = allSlices()
        .filter(p => p.installId !== mine)
        .filter(p => now - Date.parse(p.recvAt) < STALE_MS)
        .sort((a, b) => (Number((b.tot || {}).tokW) || 0) - (Number((a.tot || {}).tokW) || 0));
    json(res, 200, { updated: new Date(now).toISOString(),
        peers: identity ? rows.map(peerPublic) : rows });
}


// ── Чат ─────────────────────────────────────────────────────────────────────
// Порядок проверок не случаен: сначала бесплатные (форма тела), потом дорогие
// (декодирование вложения), и только потом антифлуд. Отвергнутый мусор не должен
// сжигать минутную квоту честных сообщений.
function handleChat(req, res, raw, me, u) {
    let m;
    try { m = JSON.parse(raw); } catch { return json(res, 400, { error: 'тело не JSON' }); }
    if (!m || typeof m !== 'object') return json(res, 400, { error: 'тело не JSON' });
    // 🔴 Личность автора. В режиме личности она из ЗАПИСИ и только из неё: подделка автора
    // умирает здесь, потому что подделывать нечего — `installId` и ник в теле не читаются.
    // В наследуемом режиме всё как было (и там же честно сказано, чего это стоит).
    let installId, nick, c;
    if (me) {
        // Группу берём из тела или из строки запроса — что удобнее звонящему; на решение
        // это не влияет, потому что дальше стоит проверка членства ПО ЗАПИСИ.
        const gid = String((m.gid !== undefined ? m.gid : u.searchParams.get('gid')) || '');
        if (!GID_RE.test(gid)) {
            return json(res, 400, { error: 'нужен gid=<группа>: у чата теперь есть «где», а не только «что»',
                hint: 'список своих групп — GET /me' });
        }
        // Право писать — членство ПО ЗАПИСИ. 403, а не 200 с пустотой: отказ по праву и
        // молчаливая поломка должны выглядеть по-разному.
        if (!inGroup(me, gid)) return json(res, 403, { error: 'ты не в этой группе' });
        installId = String(me.installId || '');
        nick = nickClean(me.nick) || 'mem-' + String(me.memberId || '0000').slice(0, 4);
        c = ctxOf(gid);
    } else {
        if (!idOk(m.installId)) return json(res, 400, { error: 'installId не похож на наш' });
        // Ник — свой nickClean. Если клиент прислал мусор, берём тот, под которым эта
        // установка уже сдаёт срезы: он тоже проверен нами и лежит на диске.
        nick = nickClean(m.nick);
        if (!nick) nick = nickClean((readSlice(m.installId) || {}).nick);
        if (!nick) return json(res, 400, { error: 'ник от 2 до 20 символов' });
        installId = m.installId;
        c = ctxOf(null);
    }
    // Ведро антифлуда — на УЧАСТНИКА, а не на присланный `installId`: последний в
    // наследуемом режиме выбирает сам звонящий, то есть сменил id — обошёл, назвался
    // чужим — сжёг чужую квоту. В режиме личности этого места больше нет.
    const bucket = me ? me.memberId : installId;
    const text = textClean(m.text);
    let att = null, type = null, name = '';

    // Одно сообщение — одно вложение, как и было: `att` это объект, а не список. Массив
    // сюда не проходит (`att.b64` у него undefined → 400), и смешать звук с картинкой
    // в одной записи нечем по построению.
    if (m.att && typeof m.att === 'object') {
        const b64 = typeof m.att.b64 === 'string' ? m.att.b64 : '';
        if (!b64) return json(res, 400, { error: 'вложение без b64' });
        let buf;
        try { buf = Buffer.from(b64, 'base64'); } catch { buf = Buffer.alloc(0); }
        // Сначала СИГНАТУРА, потом размер: пределы у картинки, звука и файла разные, и пока
        // тип не опознан, сравнивать не с чем. Поле `mime` из тела не читается ВООБЩЕ.
        type = attSniff(buf);
        if (type) {
            // Проверяемое медиа: байты сошлись с сигнатурой, значит его можно отдать со
            // своим типом содержимого, и клиент имеет право его отрисовать.
            name = '';
        } else {
            // Произвольный файл: сигнатуры у него нет и быть не может. Взамен — правило
            // отдачи: только байтами на скачивание (см. MAX_ATT_FILE и handleAtt).
            name = attName(m.att.name, m.att.ext);
            const ext = attExtOf(name, m.att.ext);
            // 🔴 Файл не имеет права выдавать себя за ПРОВЕРЯЕМОЕ медиа: с расширением из
            // белого списка клиент отрисует его картинкой или плеером, а байты мы не
            // подтвердили. Такое отвергаем, а не переименовываем молча.
            if (ATT_KIND[ext]) {
                return json(res, 415, { error: `расширение .${ext} обещает ${ATT_KIND[ext].mime},`
                        + ' а байты этого не подтверждают',
                    hint: `перечисленные форматы (${ATT_OK}) проверяются по сигнатуре;`
                        + ' любой другой файл принимается как есть и отдаётся байтами на скачивание' });
            }
            type = { ext, ...attOctet };
        }
        const max = attMax(type.kind);
        if (buf.length > max) {
            return json(res, 413, { error: `вложение ${type.ext} больше ${sizeStr(max)}`,
                bytes: buf.length, max,
                hint: type.kind === 'audio'
                    ? `${sizeStr(max)} — это около двух минут голоса в Opus; запиши короче`
                    : type.kind === 'file'
                        ? 'чат не хранилище: такой файл лучше передать иначе'
                        : 'сожми картинку сильнее' });
        }
        // Голосовых — 12 в час на участника, поверх минутного предела на сообщения. Ведро
        // трогаем только у ГОДНОГО звука: отвергнутый мусор не должен жечь честную квоту.
        // Ведро одно на человека, а не на группу: предел заведён от веса на диске ноды, а
        // диск у групп общий — «12 в час в каждой из пяти» это те же 60.
        if (type.kind === 'audio' && !rateOk(voiceRate, bucket, VOICE_PER_HOUR, 3600_000)) {
            return json(res, 429, { error: `не больше ${VOICE_PER_HOUR} голосовых в час с установки`,
                retryAfterMs: 3600_000,
                hint: 'предел на голос отдельный от 20 сообщений в минуту: звук весит в'
                    + ' тысячи раз больше текста, и кольцо журнала это место не возвращает' });
        }
        att = buf;
    }
    // Пустая строка без вложения — это не сообщение, а мусор в журнале.
    if (!text && !att) return json(res, 400, { error: 'пустое сообщение' });
    if (!chatRateOk(bucket)) {
        return json(res, 429, { error: `не больше ${CHAT_PER_MIN} сообщений в минуту`, retryAfterMs: 60_000 });
    }
    const seq = nextSeq(c);
    // Ноль значит «номер не записался» (кончилось место). Раньше на этом месте процесс
    // просто падал; теперь это честный отказ, и сообщение не теряется молча.
    if (!seq) {
        return json(res, 507, { error: 'счётчик сообщений не записался — сообщение не принято',
            hint: 'на ноде кончилось место; уже принятая переписка цела' });
    }
    const rec = { seq, installId, nick, text, recvAt: new Date().toISOString() };
    if (att) {
        // Имя файла собираем из ЧИСЛА seq, проверенного `gid` и расширения из НАШЕЙ
        // таблицы. Пришедшей строке здесь места нет: любое её попадание в путь — это
        // готовый обход каталога.
        try {
            const f = attFile(c.p, seq, type.ext);
            fs.mkdirSync(path.dirname(f), { recursive: true });
            fs.writeFileSync(f, att);
        } catch (e) { log(`чат: вложение #${seq} не записалось: ${e.message}`); return json(res, 500, { error: 'вложение не записалось' }); }
        rec.att = { bytes: att.length, ext: type.ext, kind: type.kind };
        // Длительность — подсказка отправителя (секунды). Её нельзя проверить, поэтому она
        // хранится как есть (в разумном диапазоне) и ни в одном расчёте не участвует.
        const dur = type.kind === 'audio' ? attDur(m.att.dur) : null;
        if (dur) rec.att.dur = dur;
        // Исходное имя хранится ОТДЕЛЬНО от пути: на диске файл лежит под номером
        // сообщения, а имя — здесь. Иначе это обход каталога прямым текстом.
        if (name) rec.att.name = name;
    }
    if (!chatAppend(c, rec)) {
        // Журнал не записался. Вложение уже на диске — убираем его сами, иначе получаем
        // ровно тот осиротевший файл, из-за которого заведена вся эта возня с именами.
        if (rec.att) chatDropAtt(c, rec);
        return json(res, 507, { error: 'журнал не записался — сообщение не принято',
            hint: 'на ноде кончилось место; уже принятая переписка цела, она пишется через времянку' });
    }
    log(`чат #${seq}${c.p.gid ? '/' + c.p.gid.slice(0, 8) : ''} от ${nick}`
        + ` (${installId.slice(0, 8)}), ${text.length} симв.`
        + (att ? `, вложение ${type.kind}/${type.ext} ${att.length} Б` : ''));
    json(res, 200, { ok: true, seq, ...(c.p.gid ? { gid: c.p.gid } : {}) });
}

// Ответ на чтение одной группы: `{ seq, gseq, firstSeq, cold, more, messages, gone }`.
// Форма одна и та же в обоих режимах: в наследуемом она уезжает верхним уровнем ответа,
// в режиме личности — внутри `groups[gid]`. Прежние поля (`seq`, `messages`) не
// переименованы и считаются как раньше: на них стоят клиент и приёмочные тесты.
//   `gseq`     — курсор надгробий. Клиент запоминает его после КАЖДОГО успешного чтения и
//                присылает обратно; без этого `cold` у него не погаснет.
//   `firstSeq` — самое старое сообщение, которое ещё в журнале (0 = журнал пуст). Всё ниже
//                клиент выбрасывает у себя: так описывается обрезка по лимиту, одним
//                числом вместо тысячи надгробий.
//   `cold`     — «перечислить пропавшее не могу, перечитай хвост». Ставится, когда курсор
//                клиента ниже того, что мы уже забыли (`cut`), или ВЫШЕ нашего счётчика —
//                второе значит, что состояние приёмника обнулилось (потеря файла, чужой
//                каталог данных), и врать клиенту «всё в порядке» тут нельзя.
//   `more`     — выше отданного осталось непрочитанное: опрашивать сразу, не ожидая тика.
//                Без него страница в 200 сообщений на одну группу означала бы, что тихие
//                группы отстают навсегда.
// 🔴 Пустой `gone` вместо признания запрещён: он читается как «ничего не пропало».
function feedRow(c, m) {
    const o = { seq: m.seq, installId: m.installId, nick: m.nick, text: m.text || '', recvAt: m.recvAt };
    // Ссылку СЧИТАЕМ из seq и группы, а не храним: хранимую строку однажды подменят.
    // Путь относительный — наружу вложение отдаёт хаб, а не приёмник напрямую.
    const bytes = Number((m.att || {}).bytes) || 0;
    if (bytes > 0) {
        const ext = attExt(m);
        const t = attType(ext);
        // `ext` клиенту нужен: по нему он решает, картинка это, плеер или скачивание.
        // `kind` и `mime` рядом — чтобы у него не завёлся ВТОРОЙ список форматов,
        // который однажды разъедется с нашим.
        o.att = { url: `/chat/att/${c.p.gid ? c.p.gid + '/' : ''}${m.seq}.${ext}`,
            bytes, ext, kind: t.kind, mime: t.mime };
        // Длительность — подсказка отправителя, не измеренная величина. Отдаём как есть.
        if (m.att.dur) o.att.dur = m.att.dur;
        // Имя — только для показа и для кнопки «скачать». Путь запроса из него не
        // собирается ни здесь, ни у клиента.
        if (m.att.name) o.att.name = m.att.name;
    }
    return o;
}
// Отбор кандидатов на выдачу. `tail=1` — «отдай хвост»: первое открытие группы иначе
// стоит восьми страниц с самого дна журнала. `before=<seq>` — прокрутка назад; без неё
// хвост сделал бы старое недостижимым.
function feedPick(all, since, before, tail) {
    if (before > 0) return all.filter(m => m.seq < before).slice(-CHAT_PAGE);
    const fresh = all.filter(m => m.seq > since);
    if (tail && !since) return fresh.slice(-CHAT_PAGE);
    return fresh;
}
function feedBody(c, all, cand, taken, since, cg, now) {
    const messages = taken.map(m => feedRow(c, m));
    gonePrune(c, now);
    // Курсор — seq ПОСЛЕДНЕГО отданного сообщения, а не самого свежего в журнале:
    // на упоре в 200 клиент иначе перескочил бы через неотданное. Пустая выдача
    // возвращает `since` как есть, чтобы опрос не сбрасывался в начало.
    const last = messages.length ? messages[messages.length - 1].seq : since;
    const out = { seq: last, gseq: c.gseq, firstSeq: all.length ? all[0].seq : 0,
        cold: cg < c.cut || cg > c.gseq, more: cand.length > taken.length, messages,
        gone: c.gone.filter(g => g.gseq > cg).map(g => ({ seq: g.seq, at: g.at, gseq: g.gseq })) };
    if (out.cold) {
        out.coldWhy = cg > c.gseq
            ? `твой курсор надгробий ${cg} выше нашего ${c.gseq}: состояние приёмника обнулялось`
            : `надгробия до ${c.cut} уже забыты, а твой курсор ${cg} ниже — перечислить пропавшее нечем`;
    }
    return out;
}
const intAt = (v, d = 0) => { const n = Number.parseInt(v || '', 10); return Number.isFinite(n) && n >= 0 ? n : d; };
// Курсор в режиме личности — карта `cur=<gid>:<seq>:<gseq>[,…]`, один запрос за тик
// независимо от числа групп. Разбор СТРОГИЙ: `gid` только 32 hex, числа только целые ≥ 0,
// групп не больше 16, а сломанная запись — 400 с описанием ожидаемого (присланное в ответ
// не возвращаем: оно уедет в разметку вкладки). Молчаливая обрезка запрещена: молча
// отброшенная группа никогда не обновится, и заметить это неоткуда.
const CUR_MAX = 16;
function curParse(raw) {
    const parts = String(raw).split(',').map(s => s.trim()).filter(Boolean);
    if (!parts.length) return { error: 'пустой cur=' };
    if (parts.length > CUR_MAX) return { error: `групп в запросе больше ${CUR_MAX}` };
    const out = [];
    for (const p of parts) {
        const m = /^([a-f0-9]{32}):(\d{1,15}):(\d{1,15})$/.exec(p);
        if (!m) return { error: 'ждём cur=<32 hex>:<seq>:<gseq>[,…]' };
        if (out.some(x => x.gid === m[1])) return { error: 'одна и та же группа в cur= дважды' };
        out.push({ gid: m[1], since: Number(m[2]), cg: Number(m[3]) });
    }
    return { list: out };
}
function handleChatFeed(req, res, u, me) {
    const now = Date.now();
    const tail = u.searchParams.get('tail') === '1';
    const before = intAt(u.searchParams.get('before'));
    if (!me) {
        const c = ctxOf(null);
        const since = intAt(u.searchParams.get('since'));
        const cg = intAt(u.searchParams.get('gseq'));
        const all = chatAll(c);
        const cand = feedPick(all, since, before, tail);
        return json(res, 200, feedBody(c, all, cand, cand.slice(0, CHAT_PAGE), since, cg, now));
    }
    const curRaw = u.searchParams.get('cur');
    const gidOne = String(u.searchParams.get('gid') || '');
    if (curRaw === null && !gidOne) {
        // 🔴 Громкий отказ, а не «отдам основание по умолчанию». Молчаливый дефолт здесь
        // это раздача чата друзей любому, кто ходит по старому контракту, — и он же
        // означает, что смысл `all=1`/`mine=1` перестаёт быть определённым.
        return json(res, 400, { error: 'у чата теперь есть «где»: нужен gid=<группа> либо'
                + ' cur=<gid>:<seq>:<gseq>[,…]',
            hint: 'список своих групп — GET /me; одним запросом по всем группам — cur=' });
    }
    if (curRaw === null) {
        if (!GID_RE.test(gidOne)) return json(res, 400, { error: 'gid — 32 символа [a-f0-9]' });
        // Не член — 200 с пустотой и явной пометкой, а не 401 и не 500: молчаливая поломка
        // и отказ по праву должны выглядеть по-разному. И приёмник НЕ различает «тебя
        // исключили», «группу удалили» и «ты ещё не переложил конфиг»: тот же ответ
        // получает честный член, и угадывать здесь нечего.
        if (!inGroup(me, gidOne)) {
            return json(res, 200, { gid: gidOne, seq: 0, gseq: 0, firstSeq: 0, cold: false,
                more: false, messages: [], gone: [], notMember: true,
                why: 'ты не в этой группе' });
        }
        const c = ctxOf(gidOne);
        const since = intAt(u.searchParams.get('since'));
        const cg = intAt(u.searchParams.get('gseq'));
        const all = chatAll(c);
        const cand = feedPick(all, since, before, tail);
        return json(res, 200, { gid: gidOne,
            ...feedBody(c, all, cand, cand.slice(0, CHAT_PAGE), since, cg, now) });
    }
    const parsed = curParse(curRaw);
    if (parsed.error) return json(res, 400, { error: parsed.error });
    const groups = {}, unknown = [];
    const slots = [];
    for (const it of parsed.list) {
        // Неизвестная нам или чужая группа уезжает в `unknown[]`, а не роняет весь ответ:
        // одна мёртвая группа не имеет права ослепить остальные.
        if (!inGroup(me, it.gid)) { unknown.push(it.gid); continue; }
        const c = ctxOf(it.gid);
        const all = chatAll(c);
        slots.push({ it, c, all, cand: feedPick(all, it.since, before, tail), take: 0 });
    }
    // Страница — 200 сообщений НА ВЕСЬ ОТВЕТ, и распределяются они по кругу. Иначе
    // болтливая группа всегда съедает страницу целиком, а тихие отстают навсегда.
    let left = CHAT_PAGE, moved = true;
    while (left > 0 && moved) {
        moved = false;
        for (const s of slots) {
            if (left <= 0) break;
            if (s.take >= s.cand.length) continue;
            s.take++; left--; moved = true;
        }
    }
    for (const s of slots) {
        groups[s.it.gid] = feedBody(s.c, s.all, s.cand, s.cand.slice(0, s.take),
            s.it.since, s.it.cg, now);
    }
    json(res, 200, { updated: new Date(now).toISOString(), groups, unknown });
}


// Отдача вложения. `seq` сюда приходит уже числом, а `gid` и расширение — прошедшими
// проверку (см. ATT_RE / ATT_GRP_RE в диспетчере), так что склеить путь наружу каталога
// нечем.
// 🔴 В режиме личности отдача ТОЖЕ проверяет членство: иначе адрес картинки становится
// неаутентифицированным каналом в чужую переписку — а это ровно то, что владелец просил
// закрыть. Проверка одна и та же, что у чтения ленты, и опирается на запись участника.
// Кеширование: `no-store` вместо суточного `max-age`. Причина не в экономии — наоборот:
// с `max-age=86400` картинка СНЯТОГО сообщения открывалась ещё сутки из дискового кеша
// браузера, то есть удаление выглядело сделанным, а байты оставались доступны. Взамен
// ставится `ETag`: номер сообщения не переиспользуется, файл пишется один раз и больше не
// переписывается, значит `<seq>-<размер>` — точный, а не эвристический отпечаток, и
// повторное чтение через хаб стоит 304 (~300 Б) вместо полной перекачки.
// Честная оговорка: файл, который человек уже скачал себе, не стирает НИ ОДИН вариант.
function handleAtt(req, res, gid, seq, ext, me) {
    const t = attType(ext);
    // Ведро отдачи — на участника в режиме личности: иначе один качающий вложения циклом
    // выбивает картинки у остальных.
    if (!rateOk(attRate, me ? 'att:' + me.memberId : 'att', ATT_PER_MIN)) {
        return json(res, 429, { error: `не больше ${ATT_PER_MIN} вложений в минуту `
                + (me ? 'на участника' : 'на ключ'),
            retryAfterMs: 60_000,
            hint: 'это предел на ОТДАЧУ файлов; перерисовка страницы в него не упирается' });
    }
    if (me && !inGroup(me, gid)) return json(res, 403, { error: 'ты не в этой группе' });
    const c = ctxOf(gid);
    const file = attFile(c.p, seq, ext);
    let st;
    try { st = fs.statSync(file); } catch { return json(res, 404, { error: 'вложения нет' }); }
    const etag = `"${seq}-${st.size}"`;
    const asked = String(req.headers['if-none-match'] || '').split(',').map(s => s.trim());
    if (asked.includes(etag) || asked.includes('*')) {
        res.writeHead(304, { ETag: etag, 'Cache-Control': 'no-store' });
        return res.end();
    }
    let buf;
    try { buf = fs.readFileSync(file); } catch { return json(res, 404, { error: 'вложения нет' }); }
    const head = { 'Content-Type': t.mime, 'Content-Length': buf.length,
        'Cache-Control': 'no-store', ETag: etag, 'X-Content-Type-Options': 'nosniff' };
    if (t.kind === 'file') {
        // 🔴 Произвольный файл уезжает ТОЛЬКО байтами на скачивание. Имя берётся из записи
        // журнала (санировано при приёме) и кодируется дважды: ASCII-запасной вариант в
        // кавычках и `filename*` для всего остального — иначе кириллическое имя разорвёт
        // заголовок. Замер на Node v24.16.0: любой символ выше U+00FF, а также CR, LF и NUL
        // в значении заголовка дают `ERR_INVALID_CHAR`, то есть `filename*` здесь не «хорошая
        // практика», а единственный работающий путь.
        // 🪤 `encodeURIComponent` оставляет `'()*` нетронутыми, а их нет в допустимом наборе
        // для этого поля — и апостроф ломает саму рамку `кодировка'язык'значение`. Поэтому
        // они докодируются вручную: иначе файл с именем `it's mine.md` даёт битый заголовок.
        // И `nosniff` тут НЕ замена `attachment`: алгоритм определения типа по содержимому
        // начинается с «если заявленный тип HTML или XML — берём заявленный», а блокировка по
        // `nosniff` касается только скриптов и стилей. Спасает именно `attachment`.
        const rec = chatAll(c).find(x => x.seq === seq);
        const nm = (rec && rec.att && rec.att.name) || `${seq}.${ext}`;
        const ascii = nm.replace(/[^\w.\-]+/g, '_') || `${seq}.${ext}`;
        const pct = encodeURIComponent(nm)
            .replace(/['()*]/g, c2 => '%' + c2.charCodeAt(0).toString(16).toUpperCase());
        head['Content-Disposition'] = `attachment; filename="${ascii}"; filename*=UTF-8''${pct}`;
    }
    res.writeHead(200, head);
    res.end(buf);
}
const ATT_RE = /^\/chat\/att\/(\d{1,15})\.([a-z0-9]{1,8})$/;
const ATT_GRP_RE = /^\/chat\/att\/([a-f0-9]{32})\/(\d{1,15})\.([a-z0-9]{1,8})$/;

// ── Своя запись и свои группы ────────────────────────────────────────────────
// `GET /me` — отдельная ручка ровно потому, что `/health` трогать нельзя: на нём висят
// приёмка выката, доказательство подключения в `league-join.js` и сквозная проверка.
// «Знает ли приёмник про мою личность» спрашивается здесь.
function groupBrief(me, gid) {
    const g = groupOf(gid);
    if (!g) return { gid, title: '', unknown: true };
    return { gid, title: g.title || '', createdBy: g.createdBy || null,
        createdAt: g.createdAt || null, mine: g.createdBy === me.memberId,
        members: Array.isArray(g.members) ? g.members.length : 0 };
}
function handleMe(req, res, me) {
    json(res, 200, { ok: true, memberId: me.memberId, installId: me.installId || null,
        nick: me.nick || '', status: me.status, createdAt: me.createdAt || null,
        invitedBy: me.invitedBy || null,
        groups: (Array.isArray(me.groups) ? me.groups : []).map(g => groupBrief(me, g)) });
}
// Состав группы — единственное место, где наружу уезжают лицо, `installId`, `ver`, `sha` и
// часовой пояс, и только ЧЛЕНАМ этой группы. `rid` считается той же функцией, что в
// публичной выдаче, поэтому клиент склеивает доску и состав сам, без ветвления на сервере.
function handleGroupGet(req, res, gid, me) {
    if (!inGroup(me, gid)) return json(res, 403, { error: 'ты не в этой группе' });
    const g = groupOf(gid);
    if (!g) return json(res, 404, { error: 'такой группы нет' });
    const st = membersState();
    const ids = Array.isArray(g.members) ? g.members : [];
    const members = ids.map(mid => {
        const rec = (st.map || {})[mid] || {};
        const s = rec.installId ? readSlice(rec.installId) : null;
        const out = { memberId: mid, nick: rec.nick || '', status: rec.status || 'unknown',
            installId: rec.installId || null, invitedBy: rec.invitedBy || null,
            rid: rec.installId ? ridOf(rec.installId) : null };
        if (s) {
            out.lastAt = s.recvAt || null;
            if (s.avatar) out.avatar = s.avatar;
            if (s.ver) out.ver = s.ver;
            if (s.sha) out.sha = s.sha;
            if (s.tzOffsetMin !== undefined) out.tzOffsetMin = s.tzOffsetMin;
        }
        return out;
    });
    json(res, 200, { ok: true, gid, title: g.title || '', createdBy: g.createdBy || null,
        createdAt: g.createdAt || null, mine: g.createdBy === me.memberId, members });
}


// ── Приглашения ──────────────────────────────────────────────────────────────
// Схема записи и ПОРЯДОК ПРОВЕРОК взяты у готовых решений (Prosody, Headscale, Zulip,
// Matrix), потому что четыре независимые реализации сходятся почти до имён полей — а вот
// код у них либо не переиспользуем, либо под GPL/AGPL. Запись в `invites.json`, ключ —
// хеш кода:
//   { by, groups, expires, maxUses, uses, enabled, createdAt, usedBy: { <memberId>: ISO } }
// `usedBy` — это и есть та самая «отдельная запись, кто разменял, СОСТАВНЫМ ключом»
// (codeHash — ключ карты снаружи, memberId — внутри). Деталь бесплатная и неочевидная:
// без неё повторный ввод того же кода тем же человеком сжигает лишнее использование, и
// многоразовое приглашение на трёх друзей кончается на первом же, кто нажал дважды.
const titleClean = v => String(v == null ? '' : v).replace(/[\u0000-\u001F\u007F]/g, '')
    .replace(/\p{Cf}/gu, '').replace(/\s+/g, ' ').trim().slice(0, MAX_TITLE);
// Отпечаток своего сертификата — чтобы приглашение было ОДНОЙ строкой, а не ритуалом из
// трёх значений, которые владелец диктует в личку. Считается как у хаба: sha256 от DER
// листового сертификата, заглавным hex. Нет сертификата или адреса — блоба просто нет, и
// в ответе сказано почему; код при этом выдан и работает.
let pinCache = null;
function certPin() {
    if (pinCache !== null) return pinCache;
    pinCache = '';
    try {
        const pem = fs.readFileSync(process.env.TLS_CERT || '', 'utf8');
        const m = /-----BEGIN CERTIFICATE-----([\s\S]*?)-----END CERTIFICATE-----/.exec(pem);
        if (m) pinCache = sha256(Buffer.from(m[1].replace(/\s+/g, ''), 'base64')).toUpperCase();
    } catch { /* сертификата нет — работаем по HTTP, блоб не собираем */ }
    return pinCache;
}
function inviteBlob(code) {
    const url = String(process.env.LEAGUE_URL || process.env.PUBLIC_URL || '').replace(/\/+$/, '');
    const pin = certPin();
    if (!url) return { why: 'адрес приёмника ему самому неизвестен: строку подключения'
            + ' собирает хаб (у него в league-config.json есть и url, и pin)' };
    const body = { v: 1, u: url, ...(pin ? { p: pin } : {}), c: code };
    return { blob: 'xgl1_' + Buffer.from(JSON.stringify(body), 'utf8').toString('base64url') };
}
// 🔴 Порядок проверок и есть логика, поэтому он взят дословно у `Validate()` Headscale:
//   погашено → просрочено → многоразовое? → уже использовано.
// И обе наследуемые ловушки того кода закрыты явно:
//   🪤 пустой или нечитаемый срок = ПРОСРОЧЕНО, а не «никогда не истекает». В Headscale
//      `expires = null` означает вечный код, то есть поле, забытое при создании, открывает
//      вход навсегда;
//   🪤 многоразовый ключ у него проверку «уже использовано» ПРОПУСКАЕТ вообще. Здесь она
//      действует и для многоразового — просто считает размены по составному ключу и
//      разрешает их несколько.
// Плюс проверка, которой в готовых решениях нет: право приглашать сверяется у ПОРУЧИТЕЛЯ в
// момент размена, а не только при выдаче. Без неё отзыв участника оставлял бы за ним живые
// входы в группу (поведение Zulip при деактивации автора приглашений).
function inviteValidate(inv, memberId, now) {
    if (!inv || typeof inv !== 'object') return { code: 404, error: 'такого приглашения нет' };
    // 1. Погашено вручную либо поручитель больше не активный участник.
    if (inv.enabled === false) return { code: 410, error: 'приглашение погашено' };
    const by = memberOf(inv.by);
    if (!by || by.status !== 'active') {
        return { code: 410, error: 'пригласивший больше не участник лиги —'
                + ' его непогашенные приглашения не действуют' };
    }
    const groups = (Array.isArray(inv.groups) ? inv.groups : []).filter(g => GID_RE.test(g));
    if (!groups.length) return { code: 410, error: 'приглашение ни в одну группу не ведёт' };
    if (!groups.every(g => inGroup(by, g))) {
        return { code: 410, error: 'пригласивший сам больше не в этой группе' };
    }
    // 2. Просрочено. Пустой и нечитаемый срок — сюда же, это не «вечное».
    const exp = Date.parse(inv.expires);
    if (!Number.isFinite(exp)) {
        return { code: 410, error: 'у приглашения нет читаемого срока — считаем просроченным',
            hint: 'поле срока, забытое при создании, не должно открывать вход навсегда' };
    }
    if (exp <= now) return { code: 410, error: 'приглашение просрочено' };
    // 3. Многоразовое? У Headscale здесь выход из проверок, и это его вторая ловушка.
    const maxUses = Math.max(1, Math.min(INVITE_MAX_USES, Number(inv.maxUses) || 1));
    const multi = maxUses > 1;
    // 4. Уже использовано — и для одноразового, и для МНОГОРАЗОВОГО. Сначала составной
    //    ключ: тот же человек второй раз лишнего использования не жжёт, ему просто
    //    повторяют ответ.
    const usedBy = (inv.usedBy && typeof inv.usedBy === 'object') ? inv.usedBy : {};
    if (memberId && usedBy[memberId]) return { replay: true, groups, maxUses, multi };
    const uses = Object.keys(usedBy).length;
    if (uses >= maxUses) {
        return { code: 409, error: multi
            ? `приглашение израсходовано: ${uses} из ${maxUses}`
            : 'приглашение уже использовано',
        hint: 'одноразовость сама себя доказывает: если ты его не разменивал — код взял'
                + ' кто-то другой, скажи пригласившему' };
    }
    return { groups, maxUses, multi, uses };
}
function handleInvite(req, res, body, me) {
    if (!rateOk(keyRate, 'invite:' + me.memberId, INVITE_PER_HOUR, 3600_000)) {
        return json(res, 429, { error: `не больше ${INVITE_PER_HOUR} приглашений в час`,
            retryAfterMs: 3600_000 });
    }
    const mine = Array.isArray(me.groups) ? me.groups.filter(g => GID_RE.test(g)) : [];
    if (!mine.length) return json(res, 403, { error: 'приглашать можно только в свою группу,'
            + ' а ты пока ни в одной' });
    let groups = body.groups;
    if (groups === undefined || groups === null) {
        // Умолчание есть только когда группа ровно одна: иначе неосторожное приглашение
        // отдало бы человеку сразу все твои группы.
        if (mine.length !== 1) {
            return json(res, 400, { error: 'у тебя больше одной группы — назови явно, куда'
                    + ' приглашаешь', groups: mine });
        }
        groups = [mine[0]];
    }
    if (!Array.isArray(groups) || !groups.length || groups.length > 8) {
        return json(res, 400, { error: 'groups — список из 1..8 идентификаторов групп' });
    }
    // 🔴 Право приглашать проверяет ПРИЁМНИК по записи поручителя, а не флаг от клиента.
    // Без этой проверки «любой участник группы может пригласить» незаметно превращается в
    // «любой держатель токена может пригласить куда угодно».
    for (const g of groups) {
        if (!GID_RE.test(String(g))) return json(res, 400, { error: 'gid — 32 символа [a-f0-9]' });
        if (!inGroup(me, g)) return json(res, 403, { error: 'ты не в этой группе' });
    }
    const hours = body.ttlHours === undefined ? 24 : Number(body.ttlHours);
    if (!Number.isFinite(hours) || hours <= 0) {
        return json(res, 400, { error: 'ttlHours — положительное число часов' });
    }
    const ttl = Math.min(hours * 3600_000, INVITE_TTL_MAX_MS);
    const uses = body.uses === undefined ? 1 : Number(body.uses);
    if (!Number.isInteger(uses) || uses < 1 || uses > INVITE_MAX_USES) {
        return json(res, 400, { error: `uses — целое от 1 до ${INVITE_MAX_USES}` });
    }
    const now = Date.now();
    // ≥120 бит случайности. Хранится ХЕШ: в `journalctl` и в снимках каталога живого кода
    // не остаётся, открытым текстом он существует один раз — в этом ответе.
    const code = crypto.randomBytes(16).toString('base64url');
    const id = sha256(code);
    const map = { ...invitesMap() };
    // Держим последние INVITE_KEEP записей: приглашения истекают, а файл расти вечно не
    // должен. Метём самые старые ПОГАШЕННЫЕ и просроченные, живые не трогаем.
    const keys = Object.keys(map);
    if (keys.length >= INVITE_KEEP) {
        const dead = keys.filter(k => map[k] && (map[k].enabled === false
            || !(Date.parse(map[k].expires) > now)));
        for (const k of dead.slice(0, Math.max(1, keys.length - INVITE_KEEP + 1))) delete map[k];
    }
    map[id] = { by: me.memberId, groups: groups.map(String), expires: new Date(now + ttl).toISOString(),
        maxUses: uses, enabled: true, createdAt: new Date(now).toISOString(), usedBy: {} };
    if (!writeState(INVITES_FILE, map, 0o600)) {
        return json(res, 507, { error: 'invites.json не записался — приглашение не выдано' });
    }
    // В лог уезжает только `id` (он же хеш кода) — ни значения, ни хеша целиком.
    log(`приглашение выдано участником ${me.memberId} в ${groups.map(g => g.slice(0, 8)).join(',')}:`
        + ` id ${id.slice(0, 8)}, ${uses} размен(а), срок ${Math.round(ttl / 3600_000)} ч`);
    const env = inviteBlob(code);
    json(res, 200, { ok: true, id, code, expires: map[id].expires, groups: map[id].groups,
        maxUses: uses, ...env,
        note: 'код показан ОДИН раз: на диске лежит только его sha256' });
}
function handleInviteList(req, res, me) {
    const now = Date.now();
    const map = invitesMap();
    const out = [];
    for (const [id, inv] of Object.entries(map)) {
        if (!inv || typeof inv !== 'object') continue;
        const groups = Array.isArray(inv.groups) ? inv.groups : [];
        // Видно своё и всё, что ведёт в группы, которые ты создал: гасить чужое — право
        // создателя, значит он обязан это чужое видеть.
        const canSee = inv.by === me.memberId || groups.some(g => isCreator(me, g));
        if (!canSee) continue;
        out.push({ id, by: inv.by, groups, expires: inv.expires || null,
            maxUses: Number(inv.maxUses) || 1,
            uses: Object.keys((inv.usedBy && typeof inv.usedBy === 'object') ? inv.usedBy : {}).length,
            enabled: inv.enabled !== false,
            expired: !(Date.parse(inv.expires) > now), createdAt: inv.createdAt || null });
    }
    out.sort((a, b) => String(b.createdAt).localeCompare(String(a.createdAt)));
    json(res, 200, { ok: true, invites: out });
}
function handleInviteRevoke(req, res, id, me) {
    const map = { ...invitesMap() };
    const inv = map[id];
    if (!inv) return json(res, 404, { error: 'такого приглашения нет' });
    const groups = Array.isArray(inv.groups) ? inv.groups : [];
    if (inv.by !== me.memberId && !groups.some(g => isCreator(me, g))) {
        return json(res, 403, { error: 'погасить можно своё приглашение или любое в группе,'
                + ' которую ты создал' });
    }
    map[id] = { ...inv, enabled: false, revokedAt: new Date().toISOString() };
    if (!writeState(INVITES_FILE, map, 0o600)) {
        return json(res, 507, { error: 'invites.json не записался — приглашение не погашено' });
    }
    log(`приглашение ${id.slice(0, 8)} погашено участником ${me.memberId}`);
    json(res, 200, { ok: true, id, enabled: false });
}
// 🔴 Токен нового участника делает ПРИЁМНИК, а не пригласивший. Двухшаговая выдача
// (код → размен → свой токен) реализована дважды в готовых решениях (Headscale, Prosody:
// «админ никогда не генерирует и не видит пароль другого пользователя»), и альтернатива —
// «пригласивший сам придумывает другу токен» — отвергнута ровно потому, что тогда
// пригласивший НАВСЕГДА знает чужой секрет. Это тот же дефект, что мы лечим, только не
// общий на шестерых, а попарный.
// Ручка без секрета, и она СОЗДАЁТ личность — отсюда два ведра частоты (на адрес и общее).
// Токен УЖЕ ЕСТЬ у звонящего? Тогда он не новый человек: код разменивается в его же запись
// (это вход в ещё одну группу), а повторный ввод того же кода тем же человеком возвращает
// прежний ответ и лишнего использования не жжёт.
function handleJoin(req, res, raw) {
    const addr = addrOf(req) || 'нет-адреса';
    if (!rateOk(keyRate, 'join', JOIN_PER_MIN_ALL) || !rateOk(joinRate, addr, JOIN_PER_MIN)) {
        return json(res, 429, { error: 'слишком много попыток размена приглашения',
            retryAfterMs: 60_000 });
    }
    let b;
    try { b = JSON.parse(raw); } catch { return json(res, 400, { error: 'тело не JSON' }); }
    if (!b || typeof b !== 'object') return json(res, 400, { error: 'тело не JSON' });
    // Код принимаем и голым, и внутри блоба `xgl1_…`: человек вставляет то, что ему дали.
    let code = typeof b.code === 'string' ? b.code.trim() : '';
    const inviteStr = typeof b.invite === 'string' ? b.invite.trim() : '';
    if (!code && inviteStr) {
        if (!/^xgl1_[A-Za-z0-9_-]{8,4096}$/.test(inviteStr)) {
            return json(res, 400, { error: 'это не приглашение лиги: ждём строку xgl1_…' });
        }
        try {
            const j = JSON.parse(Buffer.from(inviteStr.slice(5), 'base64url').toString('utf8'));
            code = typeof (j || {}).c === 'string' ? j.c.trim() : '';
        } catch { return json(res, 400, { error: 'приглашение не разбирается' }); }
    }
    if (!code || code.length > 200) return json(res, 400, { error: 'нужен code или invite' });
    const now = Date.now();
    const id = sha256(code);
    const invites = { ...invitesMap() };
    const existing = authOf(req);
    const v = inviteValidate(invites[id], existing && existing.memberId, now);
    if (v.code) {
        log(`размен приглашения ${id.slice(0, 8)} отклонён с ${addr}: ${v.error}`);
        return json(res, v.code, { error: v.error, ...(v.hint ? { hint: v.hint } : {}) });
    }
    const st = membersState();
    const members = { ...(st.map || {}) };
    if (v.replay) {
        // Повтор тем же человеком: ответ прежний, использование не жжётся, токен НЕ
        // переиздаётся (переиздание превратило бы двойное нажатие в потерю доступа).
        return json(res, 200, { ok: true, replay: true, memberId: existing.memberId,
            groups: existing.groups || [],
            note: 'этот код ты уже разменивал: новый токен не выдаётся, лишнее'
                + ' использование не сжигается' });
    }
    let memberId = existing ? existing.memberId : '';
    let token = '';
    if (!memberId) {
        if (Object.keys(members).length >= MAX_MEMBERS) {
            return json(res, 507, { error: `участников уже ${Object.keys(members).length},`
                    + ' новые не принимаются' });
        }
        do { memberId = crypto.randomBytes(8).toString('hex'); } while (members[memberId]);
        token = crypto.randomBytes(24).toString('base64url');
    }
    // Порядок записи: СНАЧАЛА жжём использование, потом заводим участника. Наоборот было бы
    // «участник есть, а код ещё живой», то есть утёкшее приглашение впустило бы второго
    // незнакомца. Обратная цена названа честно: если после этого не запишется
    // `members.json` (кончилось место на ноде), использование сгорело зря и другу нужно
    // новое приглашение — это дешевле лишнего входа.
    invites[id] = { ...invites[id],
        usedBy: { ...((invites[id].usedBy && typeof invites[id].usedBy === 'object') ? invites[id].usedBy : {}),
            [memberId]: new Date(now).toISOString() } };
    if (!writeState(INVITES_FILE, invites, 0o600)) {
        return json(res, 507, { error: 'invites.json не записался — размен не выполнен' });
    }
    const was = members[memberId];
    const groups = [...new Set([...(was && Array.isArray(was.groups) ? was.groups : []), ...v.groups])];
    members[memberId] = was
        ? { ...was, groups }
        // Форма записи — ровно та, что создаёт `tools/league-migrate.js`. `installId`
        // намеренно пустой: он прибивается ПЕРВЫМ принятым срезом (см. sliceIdentity).
        : { memberId, tokenHash: sha256(token), installId: '', nick: '', groups,
            status: 'active', createdAt: new Date(now).toISOString(), invitedBy: invites[id].by };
    if (!writeState(MEMBERS_FILE, members, 0o600)) {
        return json(res, 507, { error: 'members.json не записался — участник не заведён',
            hint: 'использование приглашения при этом уже сожжено: попроси новое' });
    }
    // Реестр групп — справочный, но держать его в согласии обязаны мы: интерфейс читает
    // состав именно оттуда.
    const gmap = { ...groupsMap() };
    let gDirty = false;
    for (const g of v.groups) {
        const grp = gmap[g];
        if (!grp) continue;
        const list = Array.isArray(grp.members) ? grp.members : [];
        if (list.includes(memberId)) continue;
        if (list.length >= MAX_GROUP_MEMBERS) {
            // Молча пропустить нельзя: доступ у человека есть (он живёт в его записи), а в
            // списке для интерфейса его не будет — и объяснить это станет нечем.
            log(`группа ${g.slice(0, 8)} переполнена (${list.length}): участник ${memberId}`
                + ' доступ получил, но в списке состава его нет');
            continue;
        }
        gmap[g] = { ...grp, members: [...list, memberId] };
        gDirty = true;
    }
    if (gDirty && !writeState(GROUPS_FILE, gmap)) {
        log('groups.json не записался при размене приглашения: состав группы отстал от записи участника');
    }
    log(`приглашение ${id.slice(0, 8)} разменяно с ${addr}: участник ${memberId}`
        + `${was ? ' (уже был)' : ' (новый)'}, группы ${v.groups.map(g => g.slice(0, 8)).join(',')}`);
    json(res, 200, { ok: true, memberId, groups,
        ...(token ? { token, note: 'токен показан ОДИН раз: положи его в'
            + ' routing/league-config.json полем key и сохрани копию вне репозитория' } : {}),
        invitedBy: invites[id].by });
}

// ── Группы ───────────────────────────────────────────────────────────────────
// Создать группу может любой участник, становясь её создателем: иначе владелец —
// бутылочное горлышко в инструменте, смысл которого автономность, и «друзья друзей» не
// смогут завести свою комнату без него. Цена — счёт групп на диске ноды, отсюда MAX_GROUPS
// и предел членов; это ограждения, а не политика.
function handleGroupCreate(req, res, body, me) {
    const gmap = { ...groupsMap() };
    if (Object.keys(gmap).length >= MAX_GROUPS) {
        return json(res, 507, { error: `групп уже ${Object.keys(gmap).length}, новые не создаются` });
    }
    const title = titleClean(body.title) || 'Без названия';
    const gid = crypto.randomBytes(16).toString('hex');
    const at = new Date().toISOString();
    gmap[gid] = { gid, title, createdBy: me.memberId, createdAt: at, members: [me.memberId] };
    const st = membersState();
    const members = { ...(st.map || {}) };
    const cur = members[me.memberId];
    if (!cur) return json(res, 409, { error: 'твоей записи участника нет — группу не на кого записать' });
    members[me.memberId] = { ...cur,
        groups: [...new Set([...(Array.isArray(cur.groups) ? cur.groups : []), gid])] };
    // Сначала членство в записи (это ПРАВО доступа), потом реестр: наоборот — группа,
    // в которую её же создатель не может войти.
    if (!writeState(MEMBERS_FILE, members, 0o600)) {
        return json(res, 507, { error: 'members.json не записался — группа не создана' });
    }
    if (!writeState(GROUPS_FILE, gmap)) {
        return json(res, 507, { error: 'groups.json не записался — группа не создана',
            hint: 'членство в твоей записи уже прописано; повтори запрос, когда на ноде'
                + ' появится место' });
    }
    log(`группа ${gid.slice(0, 8)} «${title}» создана участником ${me.memberId}`);
    json(res, 200, { ok: true, gid, title, createdBy: me.memberId, createdAt: at });
}
// Добавляет ЛЮБОЙ член группы — требование владельца. Право проверяет приёмник по записи
// поручителя, а не флаг от клиента.
function handleGroupAdd(req, res, gid, body, me) {
    if (!inGroup(me, gid)) return json(res, 403, { error: 'ты не в этой группе' });
    const g = groupOf(gid);
    if (!g) return json(res, 404, { error: 'такой группы нет' });
    const mid = String(body.memberId || '');
    if (!MID_RE.test(mid)) return json(res, 400, { error: 'memberId — 16 символов [a-f0-9]' });
    const st = membersState();
    const members = { ...(st.map || {}) };
    const rec = members[mid];
    if (!rec) return json(res, 404, { error: 'такого участника нет' });
    if (rec.status !== 'active') return json(res, 409, { error: 'этот участник не активен' });
    const list = Array.isArray(g.members) ? g.members : [];
    if (list.length >= MAX_GROUP_MEMBERS && !list.includes(mid)) {
        return json(res, 507, { error: `в группе уже ${list.length} участников` });
    }
    members[mid] = { ...rec,
        groups: [...new Set([...(Array.isArray(rec.groups) ? rec.groups : []), gid])] };
    if (!writeState(MEMBERS_FILE, members, 0o600)) {
        return json(res, 507, { error: 'members.json не записался — участник не добавлен' });
    }
    if (!list.includes(mid)) {
        const gmap = { ...groupsMap() };
        gmap[gid] = { ...g, members: [...list, mid] };
        if (!writeState(GROUPS_FILE, gmap)) {
            log('groups.json не записался при добавлении: состав отстал от записи участника');
        }
    }
    log(`участник ${mid} добавлен в группу ${gid.slice(0, 8)} участником ${me.memberId}`);
    json(res, 200, { ok: true, gid, memberId: mid });
}
// Исключает СОЗДАТЕЛЬ группы, и обоснование не во вкусе, а в асимметрии ущерба:
// приглашение аддитивно и отменяется дешёво (выгнать зря добавленного), а исключение
// разрушительно, и его злоупотребление видно только жертве. Право, за которым нет отката,
// не выдаётся всем. Отдельно и всегда: УЙТИ САМОМУ может каждый — единственная
// разрушительная операция, которую нельзя запрещать, это операция над собой.
// `purge=1` — третий уровень отзыва: плюс вычистить его сообщения из журнала группы.
// Опирается на уже существующую машинерию: снимок журнала перед массовым удалением и
// надгробия на каждое снятое сообщение.
function handleGroupRemove(req, res, gid, mid, u, me) {
    const g = groupOf(gid);
    if (!g) return json(res, 404, { error: 'такой группы нет' });
    const self = mid === me.memberId;
    if (!self && !isCreator(me, gid)) {
        return json(res, 403, { error: 'исключить может только создатель группы; уйти самому'
                + ' может каждый' });
    }
    const purge = u.searchParams.get('purge') === '1';
    if (purge && !isCreator(me, gid)) {
        return json(res, 403, { error: 'вычистить сообщения может только создатель группы',
            hint: 'свои сообщения убираются отдельно: DELETE /chat?gid=…&mine=1' });
    }
    const st = membersState();
    const members = { ...(st.map || {}) };
    const rec = members[mid];
    if (!rec) return json(res, 404, { error: 'такого участника нет' });
    const groups = (Array.isArray(rec.groups) ? rec.groups : []).filter(x => x !== gid);
    members[mid] = { ...rec, groups };
    // Право доступа живёт в записи участника, поэтому пишем ЕЁ первой: с этого момента
    // исключение уже действует, даже если реестр групп не обновится.
    if (!writeState(MEMBERS_FILE, members, 0o600)) {
        return json(res, 507, { error: 'members.json не записался — исключение не выполнено' });
    }
    const gmap = { ...groupsMap() };
    gmap[gid] = { ...g, members: (Array.isArray(g.members) ? g.members : []).filter(x => x !== mid) };
    if (!writeState(GROUPS_FILE, gmap)) {
        log('groups.json не записался при исключении: состав отстал от записи участника');
    }
    let purged = 0, tombs = true;
    if (purge && rec.installId) {
        const c = ctxOf(gid);
        const list = chatAll(c);
        const doomed = list.filter(x => x.installId === rec.installId);
        if (doomed.length) {
            chatBackup(c);
            const kill = new Set(doomed.map(x => x.seq));
            if (chatWriteAll(c, list.filter(x => !kill.has(x.seq)))) {
                for (const r of doomed) chatDropAtt(c, r);
                const marks = goneAdd(c, [...kill], 'purge');
                purged = doomed.length;
                tombs = marks.saved;
            } else {
                return json(res, 507, { error: 'журнал не записался — сообщения не вычищены',
                    hint: 'из группы участник уже исключён; повтори purge, когда появится место' });
            }
        }
    }
    log(`участник ${mid} ${self ? 'ушёл из' : 'исключён из'} группы ${gid.slice(0, 8)}`
        + ` (решение ${me.memberId})${purge ? `, сообщений вычищено ${purged}` : ''}`);
    json(res, 200, { ok: true, gid, memberId: mid, left: self, purged, tombs });
}
// Уйти из лиги целиком: `status: left`. После этого `authOf` записи не отдаёт, то есть все
// ручки отвечают 401 со следующего же запроса — токен не переиздаётся ни у кого.
function handleLeave(req, res, me) {
    const st = membersState();
    const members = { ...(st.map || {}) };
    const rec = members[me.memberId];
    if (!rec) return json(res, 404, { error: 'твоей записи нет' });
    members[me.memberId] = { ...rec, status: 'left', leftAt: new Date().toISOString() };
    if (!writeState(MEMBERS_FILE, members, 0o600)) {
        return json(res, 507, { error: 'members.json не записался — выход не выполнен' });
    }
    // Непогашенные приглашения ушедшего гасить отдельной записью не надо: `inviteValidate`
    // проверяет статус поручителя в момент размена, поэтому они умирают сами. Это же
    // работает и для отзыва правкой файла руками — то есть без участия кода.
    log(`участник ${me.memberId} ушёл из лиги сам (status: left)`);
    json(res, 200, { ok: true, memberId: me.memberId, status: 'left',
        note: 'токен больше не действует; вернуться можно только по новому приглашению' });
}

// TLS включается наличием сертификата: токен ходит в заголовке, и по голому HTTP его
// увидит любой на пути. Ключ и цепочку берём готовыми (на ноде их держит certbot), своей
// машинерии сертификатов здесь нет — и зависимостей тоже.
// Продление certbot'ом меняет файл, но не процесс: после renew нужен restart сервиса.
//
// Диспетчер. Врата ровно одни, и режим выбирается ОДНИМ условием — есть ли реестр
// участников. Ветвление на этом уровне, а не внутри ручек: «в этой ручке для незнакомца
// поле не отдаём» — это и есть забытый фильтр, о котором предупреждает дизайн.
const jsonBody = raw => { try { const j = JSON.parse(raw); return (j && typeof j === 'object' && !Array.isArray(j)) ? j : null; } catch { return null; } };
const badBody = res => json(res, 400, { error: 'тело не JSON-объект' });
function handler(req, res) {
    const u = new URL(req.url, `http://127.0.0.1:${PORT}`);
    // `/health` намеренно БЕЗ ключа и в обоих режимах: на нём висят приёмка выката,
    // доказательство подключения в `league-join.js` и сквозная проверка. Авторизация здесь
    // ломает все три сразу, а «знает ли приёмник про мою личность» спрашивается у `GET /me`.
    if (u.pathname === '/health') return json(res, 200, healthBody());
    const st = membersState();
    // 🔴 Файл участников есть, но не читается — 503, а не откат в наследуемый режим.
    if (st.state === 'broken') {
        return json(res, 503, { error: 'members.json на ноде не читается — приёмник не знает,'
                + ' кто есть кто, и не станет угадывать',
            hint: 'починить файл на ноде; общий ключ в этом состоянии тоже не работает —'
                + ' иначе порча файла открывала бы всё' });
    }
    if (st.state !== 'ok') return handlerLegacy(req, res, u);
    // ── Режим личности ──────────────────────────────────────────────────────
    // Публичных ручек здесь ровно две, и обе такие по решению дизайна: рейтинг читается
    // без секрета (свежая установка получает законное состояние наблюдателя, а не тихую
    // запись в чужую базу), а `/join` создаёт личность по одноразовому коду.
    // 🪤 `/peers` личность всё равно РАЗБИРАЕТ — но только чтобы не возвращать человеку
    // его собственную строку. ФОРМА ответа при этом одна на всех и не ветвится: ветвление
    // «свой/чужой» по ПОЛЯМ и есть забытый фильтр, а «какие строки» приёмник фильтрует на
    // сервере с самого начала — именно поэтому этот фильтр и работает.
    if (req.method === 'GET' && u.pathname === '/peers') {
        return handlePeers(req, res, u, authOf(req), true);
    }
    if (req.method === 'POST' && u.pathname === '/join') {
        return readBody(req, res, MAX_BODY, raw => handleJoin(req, res, raw));
    }
    const me = authOf(req);
    if (!me) {
        return json(res, 401, { error: 'токен не принят: такой личности у приёмника нет'
                + ' либо она отозвана',
            hint: 'вход в лигу только по приглашению участника (POST /join)' });
    }
    if (req.method === 'GET' && u.pathname === '/me') return handleMe(req, res, me);
    if (req.method === 'DELETE' && u.pathname === '/me') return handleLeave(req, res, me);
    if (req.method === 'GET' && u.pathname === '/chat') return handleChatFeed(req, res, u, me);
    if (req.method === 'DELETE' && (u.pathname === '/chat' || /^\/chat\/\d{1,15}$/.test(u.pathname))) {
        return handleChatDelete(req, res, u, me);
    }
    if (req.method === 'GET') {
        const a = ATT_GRP_RE.exec(u.pathname);
        if (a) return handleAtt(req, res, a[1], Number(a[2]), a[3], me);
        // Плоский адрес вложения в этом режиме больше не действует: файлы переехали в
        // подкаталог группы, и молчаливое «нет такого» прятало бы причину.
        if (ATT_RE.test(u.pathname)) {
            return json(res, 400, { error: 'у вложения теперь есть группа:'
                    + ' /chat/att/<gid>/<номер>.<расширение>' });
        }
    }
    if (req.method === 'GET' && u.pathname === '/invite') return handleInviteList(req, res, me);
    if (req.method === 'DELETE') {
        const iv = /^\/invite\/([a-f0-9]{64})$/.exec(u.pathname);
        if (iv) return handleInviteRevoke(req, res, iv[1], me);
    }
    const gm = /^\/group\/([a-f0-9]{32})$/.exec(u.pathname);
    if (req.method === 'GET' && gm) return handleGroupGet(req, res, gm[1], me);
    const gadd = /^\/group\/([a-f0-9]{32})\/member$/.exec(u.pathname);
    const gdel = /^\/group\/([a-f0-9]{32})\/member\/([a-f0-9]{16})$/.exec(u.pathname);
    if (req.method === 'DELETE' && gdel) return handleGroupRemove(req, res, gdel[1], gdel[2], u, me);
    if (req.method === 'POST') {
        if (u.pathname === '/slice') {
            return readBody(req, res, MAX_BODY, raw => handleSlice(req, res, raw, me));
        }
        if (u.pathname === '/chat') {
            return readBody(req, res, MAX_CHAT_BODY, raw => handleChat(req, res, raw, me, u));
        }
        if (u.pathname === '/invite') {
            return readBody(req, res, MAX_BODY, raw => {
                const b = jsonBody(raw); return b ? handleInvite(req, res, b, me) : badBody(res);
            });
        }
        if (u.pathname === '/group') {
            return readBody(req, res, MAX_BODY, raw => {
                const b = jsonBody(raw); return b ? handleGroupCreate(req, res, b, me) : badBody(res);
            });
        }
        if (gadd) {
            return readBody(req, res, MAX_BODY, raw => {
                const b = jsonBody(raw); return b ? handleGroupAdd(req, res, gadd[1], b, me) : badBody(res);
            });
        }
    }
    json(res, 404, { error: 'нет такой ручки' });
}
// ── Наследуемый режим: ровно то, что было до 05.09 ──────────────────────────
// Отдельной функцией, а не флагами внутри общего дерева: перепутать здесь ветку значило бы
// либо потерять живой обмен, либо открыть общим ключом то, что уже закрыто личностью.
function handlerLegacy(req, res, u) {
    if (!keyOk(req)) return json(res, 401, { error: 'нужен заголовок X-League-Key' });
    if (req.method === 'GET' && u.pathname === '/peers') return handlePeers(req, res, u, null, false);
    if (req.method === 'GET' && u.pathname === '/chat') return handleChatFeed(req, res, u, null);
    if (req.method === 'DELETE' && (u.pathname === '/chat' || /^\/chat\/\d{1,15}$/.test(u.pathname))) {
        return handleChatDelete(req, res, u, null);
    }
    if (req.method === 'GET') {
        const a = ATT_RE.exec(u.pathname);
        if (a) return handleAtt(req, res, null, Number(a[1]), a[2], null);
    }
    if (req.method === 'POST' && u.pathname === '/slice') {
        return readBody(req, res, MAX_BODY, raw => handleSlice(req, res, raw, null));
    }
    if (req.method === 'POST' && u.pathname === '/chat') {
        return readBody(req, res, MAX_CHAT_BODY, raw => handleChat(req, res, raw, null, u));
    }
    // Ручки личности в наследуемом режиме отвечают не «нет такой», а причиной: иначе выкат
    // новой сборки на непереведённые данные выглядит как сборка без этих ручек.
    if (/^\/(me|invite|join|group)(\/|$)/.test(u.pathname)) {
        return json(res, 409, { error: 'каталог данных ещё не переведён на личности:'
                + ' members.json на ноде нет',
            hint: 'перевод делает tools/league-migrate.js отдельным шагом; до него приёмник'
                + ' работает по общему ключу, как раньше' });
    }
    json(res, 404, { error: 'нет такой ручки' });
}

const TLS_CERT = process.env.TLS_CERT || '';
const TLS_KEY = process.env.TLS_KEY || '';
// 🔴 Последняя линия на случай кончившегося места. Все известные записи (журнал, счётчик,
// надгробия, снимок, срезы) отдают отказ сами — это выше и это главное. Но обработчика
// `uncaughtException` в файле не было НИ ОДНОГО, а значит любое неучтённое исключение в
// синхронной записи роняло процесс целиком: вместе с чатом останавливался и обмен срезами
// у всех шестерых. Здесь глотаются ТОЛЬКО ошибки ввода-вывода (место, права, дескрипторы):
// сервис продолжает отвечать, а беда видна в журнале ноды. Всё остальное — программная
// ошибка, и её глушить нельзя: пробрасываем дальше, процесс падает, systemd поднимает.
const IO_FATAL = new Set(['ENOSPC', 'EDQUOT', 'EROFS', 'EIO', 'EMFILE', 'ENFILE', 'EACCES', 'EPERM']);
process.on('uncaughtException', e => {
    if (!e || !IO_FATAL.has(e.code)) throw e;
    log(`ОШИБКА ДИСКА, сервис продолжает работать: ${e.code} ${e.message}`);
});
const server = (TLS_CERT && TLS_KEY)
    ? require('https').createServer(
        { cert: fs.readFileSync(TLS_CERT), key: fs.readFileSync(TLS_KEY) }, handler)
    : http.createServer(handler);
server.listen(PORT, () => log(`приёмник лиги слушает :${PORT} по ${TLS_CERT ? 'HTTPS' : 'HTTP'}, данные в ${DATA}`));
