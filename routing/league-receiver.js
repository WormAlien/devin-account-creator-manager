const sha256 = v => crypto.createHash('sha256').update(v).digest('hex');
// Сравнение хешей постоянным временем. Утечки по времени здесь и не ждут (перебрать
// sha256 предъявленного значения нельзя), но требование владельца прямое, а цена — ноль:
// оба значения фиксированной длины, значит `timingSafeEqual` применим без оговорок.
function hashEq(a, b) {
    if (!HASH_RE.test(String(a || '')) || !HASH_RE.test(String(b || ''))) return false;
    return crypto.timingSafeEqual(Buffer.from(String(a), 'hex'), Buffer.from(String(b), 'hex'));
}
