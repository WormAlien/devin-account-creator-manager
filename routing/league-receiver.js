#!/usr/bin/env node
'use strict';
// ─────────────────────────────────────────────────────────────────────────────
//  league-receiver.js — приёмник срезов «Лиги». Один файл, ноль зависимостей.
//
//  Живёт НЕ на машине владельца, а на общей ноде (сейчас планируется финская).
//  Хабы присылают ему свой срез, он раздаёт всем остальным чужие. Всё.
//
//  ── ДВА РЕЖИМА, и выбирает их РАСКЛАДКА ДАННЫХ, а не запрос ─────────────────
//  Приёмник умеет обе раскладки каталога данных, потому что выкат сборки и перевод
//  данных (`tools/league-migrate.js`) — РАЗНЫЕ шаги, и между ними проходит время:
//
//    · НАСЛЕДУЕМЫЙ режим — `members.json` в каталоге НЕТ. Работает ровно как до
//      05.09: один общий секрет из `<data>/secret`, личность приезжает в теле,
//      журнал чата плоский (`chat.ndjson`), вложения `att/<seq>.<ext>`. Это то, на
//      что выкат садится ДО перевода данных, и ломать здесь нельзя ничего: обмен
//      идёт в бою.
//    · РЕЖИМ ЛИЧНОСТИ — `members.json` есть. Предъявленный токен ищется по sha256
//      среди записей участников, и `installId`, ник и группы берутся ИЗ ЗАПИСИ;
//      тело в решениях не участвует. Чат — файл на группу (`chat/<gid>.ndjson`),
//      вложения `att|voice|files/<gid>/<seq>.<ext>`.
//
//  🔴 Общий секрет продолжает работать и после перевода — но уже как ЛИЧНЫЙ токен
//  владельца: переход кладёт в его запись `sha256(secret)`, поэтому на машине
//  владельца не правится ни один файл и обмен не замечает смены модели. Отдельной
//  «лазейки для старого ключа» в коде нет и быть не должно: она и была бы обходом
//  всей проверки прав. Если `members.json` есть, а хеша этого секрета в нём нет —
//  секрет перестаёт работать, и это ровно то, что называется отзывом.
//  🔴 Если `members.json` есть, но не читается — 503 на все ручки, а НЕ откат в
//  наследуемый режим. Молчаливое «испортился файл участников → общий ключ снова
//  открывает всё» это дыра, а не устойчивость.
//
//  Ручки (Н — наследуемый режим, Л — режим личности):
//    GET  /health         — Н Л, БЕЗ ключа: жив ли, сколько установок, когда срез.
//    POST /slice          — Н Л. Заголовок `X-League-Key: <токен>`. В Л `installId`
//                           и ник берутся из записи, из тела — нет.
//    GET  /peers          — Н: с ключом, полные срезы. Л: БЕЗ ключа и ПО БЕЛОМУ
//                           СПИСКУ — ни `installId`, ни лица, ни `ver`, ни `sha`,
//                           ни часового пояса там нет ВООБЩЕ (не «когда спросил
//                           незнакомец», а всегда: ветвление внутри публичной
//                           ручки и есть забытый фильтр).
//    POST /chat           — Н Л (+ вложение: картинка до 2 МБ, звук до 512 КБ,
//                           файл до 512 КБ; тип решают БАЙТЫ). В Л обязателен `gid`.
//    GET  /chat?since=N&gseq=G          — Н: плоская лента.
//    GET  /chat?gid=G&since=N&gseq=S    — Л: лента одной группы, та же форма.
//    GET  /chat?cur=gid:seq:gseq,…      — Л: одним запросом по всем своим группам.
//    GET  /chat/att/N.<ext>             — Н: байты вложения.
//    GET  /chat/att/<gid>/N.<ext>       — Л: то же, но членство проверяется.
//    DELETE /chat[/<seq>]               — Н: одно / все свои / `all=1`.
//    DELETE /chat?gid=G[&mine=1|&all=1] — Л: то же в пределах группы.
//    GET  /me             — Л: своя запись и свои группы.
//    POST /invite         — Л: выдать одноразовый код (любой член группы).
//    GET  /invite         — Л: свои непогашенные приглашения.
//    DELETE /invite/<id>  — Л: погасить до размена (своё — автор, любое — создатель).
//    POST /join           — Л, БЕЗ ключа: разменять код. Токен делает ПРИЁМНИК.
//    POST /group          — Л: создать группу.
//    GET  /group/<gid>    — Л: состав группы С лицами и `installId` (только членам).
//    POST /group/<gid>/member          — Л: добавить участника (любой член).
//    DELETE /group/<gid>/member/<mid>[?purge=1] — Л: исключить (создатель) или уйти
//                           самому; `purge=1` вычищает и его сообщения группы.
//    DELETE /me           — Л: уйти из лиги целиком (`status: left`).
//
//  Три уровня отзыва, и все действуют НЕМЕДЛЕННО, без рестарта юнита: `members.json`
//  и `groups.json` перечитываются по метке файла на каждом запросе, тем же приёмом,
//  каким читается журнал чата. Отзыв, вступающий в силу после `systemctl restart`,
//  отзывом не называется.
//    1. из группы — `gid` уходит из его `groups` (исключение или уход самого);
//    2. установку целиком — `status` в его записи перестаёт быть `active` (правка
//       файла владельцем ноды либо `DELETE /me`): 401 на всех ручках сразу;
//    3. и сообщения — `?purge=1` при исключении.
//  Отзыв гасит и непогашенные приглашения выгнанного: право приглашать проверяется
//  у ПОРУЧИТЕЛЯ в момент размена, а не только в момент выдачи.
//
//  Что здесь ЕСТЬ по части «не наврать»:
//    · время ставит СЕРВЕР (`recvAt`). Клиентскому `stamp` не верим вообще —
//      иначе «срез 1 мин назад» подделывается одним полем.
//    · монотонные счётчики не имеют права УБЫВАТЬ: всего токенов, всего промптов,
//      аккаунты, суммарный расход. Убыло — срез отвергнут, прошлый остаётся.
//    · рост ограничен по времени: 3 млрд токенов в час физически не бывает даже
//      у владельца (его пик — 2,2 млрд за СУТКИ), значит это накрутка. Промежуток
//      считается ДРОБНЫМИ часами: было `max(1, Δч)`, и сдача раз в минуту получала
//      целый часовой потолок каждую минуту — потолок был слабее заявленного в 60 раз.
//    · абсолютные потолки правдоподобия (`ABS_MAX`) — на КАЖДЫЙ срез, а не только на
//      второй и дальше. Потолок роста считает от предыдущего среза, а первого
//      предыдущего не бывает: до этих потолков новая установка первым же срезом
//      ставила любые конечные числа и садилась на вершину навсегда.
//    · РЯДЫ (`tok`, `sp`, `tu`, `act`, `acc`) тоже проверяются, а не только суммарные
//      пары в `tot`: клиент часть плиток считает суммой ряда, то есть график и цифры
//      рисовались чем угодно. Потолок на точку и на сумму, а где ряд и пара — по
//      построению одно число (`tokA`, `promptsAll`), там ещё и сходимость.
//    · один срез в минуту на установку И не больше `SLICE_PER_MIN` на КЛЮЧ: первое
//      обходилось сменой `installId` (его выбирает клиент), второе — нет.
//    · установок на ключе не больше `MAX_INSTALLS`, срез-файлы без обновлений
//      полгода метутся: иначе цикл со сменой id заливает ноде тысячи файлов.
//    · просадка накопительных счётчиков отвергается, но НЕ бесконечно: пять отказов
//      подряд за полчаса и больше — и новое значение принимается новой базой, событием
//      в ответе, в срезе, в логе и в файле. Иначе законная просадка (журнал токенов
//      хаба режется по 8 МБ, переустановка, чистка кеша) заклинивала участника в 409
//      навсегда: сохранённый срез выше нового и сам не истекает. Скачок ВВЕРХ такой
//      поблажки не имеет и отвергается всегда.
//    · тело до 64 КБ. Ник санируется здесь же: клиенту в вопросе разметки не верим
//      никогда.
//    · на диск идут только поля из БЕЛОГО СПИСКА (`sliceClean`), а не присланный
//      объект целиком: иначе через реле соседу передаётся что угодно, и он это
//      отрисует. Новое поле среза надо добавлять в список явно.
//    · в чате `seq` присваивает СЕРВЕР и хранит в файле, а тип вложения решают
//      БАЙТЫ (сигнатура файла), а не заявленный клиентом mime. Это верно и для звука:
//      whitelist сигнатур один на все форматы, `mime` из тела не читается вообще.
//
//  Чат, НАСЛЕДУЕМАЯ раскладка: сообщения в `<data>/chat.ndjson` (последние 1000),
//  картинки в `<data>/att/<seq>.webp`, звук ОТДЕЛЬНО в `<data>/voice/<seq>.<ext>` (у них
//  разный срок хранения), счётчик seq в `<data>/chat-seq`, надгробия удалённых — в
//  `<data>/chat-gone.json`.
//  Чат, РАСКЛАДКА ПО ГРУППАМ (её создаёт `tools/league-migrate.js`, форма файлов задана
//  там и здесь только читается): `<data>/chat/<gid>.ndjson`, `<data>/chat/<gid>.seq`,
//  `<data>/chat/<gid>.tombs.json`, вложения `<data>/att|voice|files/<gid>/<seq>.<ext>`.
//  Всё это адресуется ОДНОЙ функцией `chatPaths(gid)`, и второй сборки пути в файле
//  быть не должно: именно вторая сборка (`chatDropAtt` своей строкой `${seq}.webp`) и
//  оставляла на ноде файлы, которых уже никто не удалит. Номер сообщения — СВОЙ у
//  каждой группы: глобальный счётчик отвергнут, потому что разрывы в номерах
//  рассказывают, сколько написали в чужих группах.
//  Аватарка приезжает полем `avatar` внутри среза (data-URL webp, до 20 КБ в
//  ДЕКОДИРОВАННЫХ байтах — та же единица, что у хаба) и уезжает членам группы в
//  `GET /group/<gid>`, а в публичной выдаче `/peers` её нет вовсе. Обрезка журнала
//  до 1000 снимает и ВЛОЖЕНИЯ выпавших сообщений — раньше их не удалял никто, и
//  файл без сообщения оставался на ноде навсегда. Что переживёт и это (осиротело
//  из-за падения посреди записи) — добирает systemd по возрасту, рецепт в
//  `league-chat-tmpfiles.conf` рядом с этим файлом: 30 суток картинкам, 7 суток звуку по
//  времени МОДИФИКАЦИИ (иначе прослушивание обновляет отметку и файл не старится никогда).
//
//  Надгробия (05.09): протокол чтения умел только «добавилось», поэтому удалённое
//  сообщение висело у всех соседей до перезагрузки страницы. Теперь каждое РЕШЕНИЕ
//  ЧЕЛОВЕКА убрать сообщение — одиночное, «все свои», `all=1` — пишет номер, время и свой
//  монотонный номер `gseq` в `chat-gone.json`, а ответ на чтение несёт `gone` (надгробия
//  новее клиентского `gseq`), `firstSeq` (дно журнала — так описывается обрезка по лимиту,
//  одним числом вместо тысячи надгробий) и `cold: true`, когда перечислить пропавшее
//  нельзя. Разбор — над goneAdd и handleChatFeed.
//
//  Удаление в чате. В НАСЛЕДУЕМОМ режиме как было: своё уходит без оговорок, чужое
//  ОДНО сообщение — только с `force=1`, а на «все сообщения установки» ограды нет и
//  быть не может — проверить владение нечем, пока ключ один на шестерых (разбор в
//  handleChatDelete, и пробовать снова не надо). В РЕЖИМЕ ЛИЧНОСТИ ограда становится
//  настоящей и опирается на ЗАПИСЬ, а не на присланные поля: своё определяется
//  `installId` из записи, чужое одно сообщение сносит только СОЗДАТЕЛЬ группы (и всё
//  равно с `force=1` — осознанность нужна и ему), `all=1` тоже только создатель, а
//  `?installId=` из строки запроса не читается ВООБЩЕ — его значение не участвует ни в
//  одном решении. Последнее не мелочь: 05.09 сверка присланного `installId` с
//  «владельцем» сломала живую кнопку «убрать мои» и была откатана в тот же час.
//  Что защищает в обоих режимах: ограничение частоты на сами удаления, снимок журнала
//  в `<data>/chat-<штамп>.bak.ndjson` перед каждым массовым удалением (последние
//  `CHAT_BAK_KEEP`) и адрес запросившего в логе.
//
//  Коды отказов чата: 400 — тело/ник/пустое сообщение, 403 — чужое сообщение без
//  `force=1`, 413 — больше лимита, 415 — вложение не опознано по байтам (ни картинка,
//  ни звук из белого списка), 429 — больше 20 сообщений в минуту с установки,
//  `VOICE_PER_HOUR` голосовых в час с установки, `ATT_PER_MIN` отдач вложений или
//  `DELETE_PER_MIN` удалений в минуту на ключ, 507 — на ноде нет места: журнал или
//  счётчик не записались (раньше это роняло процесс).
//  Коды отказов среза: 400 — форма, 409 — не сходится с прошлым или выше потолков,
//  429 — частота, 507 — установок на ключе уже `MAX_INSTALLS`.
//
//  Секрет: при первом старте генерируется и печатается ОДИН раз, дальше лежит в
//  `<data>/secret`. В git он не попадает — файл создаётся на ноде. После перевода
//  данных это уже не общий ключ, а личный токен владельца (см. про два режима выше).
//  Токены участников на диске лежат только хешами (`members.json` → `tokenHash`), и
//  открытым текстом токен существует один раз — в ответе на `POST /join`. В лог ноды
//  уезжает только `id` приглашения (первые 8 символов хеша кода), никогда сам код.
//
//  Запуск:  node league-receiver.js [порт] [каталог данных]
//           PORT=8420 DATA=/opt/league node league-receiver.js
// ─────────────────────────────────────────────────────────────────────────────
const http = require('http');
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const PORT = Number(process.env.PORT || process.argv[2] || 8420);
const DATA = process.env.DATA || process.argv[3] || path.join(__dirname, 'league-data');
const SLICES = path.join(DATA, 'slices');
// ── Плоская (наследуемая) раскладка чата ────────────────────────────────────
const CHAT_FILE = path.join(DATA, 'chat.ndjson');
const ATT_DIR = path.join(DATA, 'att');
// Звук лежит ОТДЕЛЬНО от картинок, и не для порядка: срок хранения у них разный (7 суток
// против 30), а tmpfiles умеет срок только на путь целиком. Один каталог означал бы либо
// месяц голосовых на диске, либо картинки, живущие неделю.
const VOICE_DIR = path.join(DATA, 'voice');
// Произвольные файлы — третий каталог. Срок у них как у картинок (30 суток), но каталог
// свой: чтобы срок можно было развести, не переписывая имена файлов, и чтобы «что здесь
// вообще лежит» было видно по дереву, а не по расширениям в общей куче.
const FILE_DIR = path.join(DATA, 'files');
const SEQ_FILE = path.join(DATA, 'chat-seq');
const GONE_FILE = path.join(DATA, 'chat-gone.json');
// ── Раскладка по группам и файлы личности ───────────────────────────────────
// 🔴 Форму этих файлов задаёт `tools/league-migrate.js`, а не этот файл. Приёмник их
// только читает и дописывает; менять форму здесь в одностороннем порядке нельзя —
// разъедется переход, и заметить это будет неоткуда (перенос молча даст ноль записей).
const CHAT_DIR = path.join(DATA, 'chat');
const MEMBERS_FILE = path.join(DATA, 'members.json');
const GROUPS_FILE = path.join(DATA, 'groups.json');
const INVITES_FILE = path.join(DATA, 'invites.json');
// Соль хеша адреса переехала в свой файл: единого секрета в процессе больше нет, а
// раньше солью служил именно он — и любая смена доступа молча превращала учёт адресов
// в мусор. Файл создаёт переход (`addr-salt`, 64 hex); пока его нет, солью остаётся
// секрет, иначе наследуемая раскладка потеряла бы живую серию просадок на выкате.
const SALT_FILE = path.join(DATA, 'addr-salt');
const GID_RE = /^[a-f0-9]{32}$/;
const MID_RE = /^[a-f0-9]{16}$/;
const HASH_RE = /^[a-f0-9]{64}$/;

const MAX_BODY = 64 * 1024;          // срез укладывается в 64 КБ (проверено check-league.js)
// Тело чата больше самого вложения: base64 раздувает байты на треть, плюс текст и поля.
// Считается от САМОГО ТЯЖЁЛОГО вложения — это картинка (2 МБ), звук легче.
const MAX_CHAT_BODY = 3 * 1024 * 1024;
const MAX_TEXT = 2000;               // символов в сообщении
const MAX_ATT = 2 * 1024 * 1024;     // байт КАРТИНКИ после декодирования
// Отдельный предел для звука, и он НЕ про пиксели, а про ВРЕМЯ. Голос пишется в Opus на
// 24–32 кбит/с моно: 512 КБ — это ~120 секунд при 32 кбит/с и ~170 секунд при 24. Голосовое
// сообщение длиннее двух минут в чате шести человек — это уже не сообщение.
// Почему НЕ общие 2 МБ: журнал держит 1000 сообщений, и худший случай кольца из одних
// вложений — это умножение. 1000 × 2 МиБ = 2 ГиБ на диске ноды, 1000 × 512 КБ = 500 МБ.
// Разница не теоретическая: чистка по возрасту (30 суток у картинок, 7 у звука) потолок
// объёма не ставит вообще, она ставит только срок.
// Почему нет отдельного предела ДЛИТЕЛЬНОСТИ: дёшево её узнать нельзя именно у тех
// форматов, которыми пишет браузер. MediaRecorder ведёт webm потоком, и элемента
// `Duration` в заголовке у него, как правило, НЕТ вовсе (отсюда известная бесконечность в
// плеере), у фрагментированного mp4 от Safari `mvhd.duration` равен нулю. Точно и дёшево
// длительность читается только из wav (fmt+data) и из granulepos последней страницы ogg —
// то есть у форматов, которые сюда приезжают реже всего. Считать её декодированием значит
// завести в приёмнике кодек. Поэтому предел один — вес, а длительность клиент присылает
// ПОДСКАЗКОЙ (`att.ms`), и проверить её нечем: см. attMs.
const MAX_ATT_AUDIO = 512 * 1024;    // байт ЗВУКА после декодирования
