// ⚠️ Это НЕ проверка прав и не может ею стать НИ В ОДНОМ из двух режимов. В наследуемом
// приёмник не знает, кто к нему обратился (секрет один на шестерых), а в режиме личности
// адрес всё равно бесполезен как право: у честного хаба он меняется (динамический IP,
// переезд, мобильный), и проверка по нему замкнула бы участника в отказе. Проверку
// владения в удалении пробовали 05.09 и откатили в тот же час — см. handleChatDelete.
// Здесь адрес нужен ровно для двух вещей, и обе — видимость, а не запрет:
//   · серия отказов по просадке считается ПО ОДНОМУ адресу (иначе «одна установка
//     просела» и «пятеро постучали по разу» — одно и то же событие);
//   · в событии пересчёта базы написано, тот же это адрес, с которого приходят срезы,
//     или другой. Понадобится разбираться, кто кому обнулил базу — будет с чего начать.
// Хранится СОЛЁНЫЙ ХЕШ адреса, а не адрес, и наружу файл не отдаётся НИКАКОЙ ручкой:
// IPv4 из солёного хеша перебирается за минуты, так что поле в срезе означало бы раздачу
// участникам чужих адресов. Соль — отдельный файл `addr-salt` (см. addrSalt): раньше ею
// служил общий секрет, и смена доступа молча превращала оба файла учёта в мусор.
const OWNERS_FILE = path.join(DATA, 'slice-owners.json');
const addrOf = req => String((req.socket && req.socket.remoteAddress) || '').replace(/^::ffff:/, '');
const addrTag = a => crypto.createHash('sha256').update(addrSalt() + '|' + a).digest('hex').slice(0, 16);
let owners = {};
