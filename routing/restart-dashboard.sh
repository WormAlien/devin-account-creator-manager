#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
#  routing/restart-dashboard.sh — форвардер. Реализация одна: hub.js.
#
#  Здесь была вторая копия жизненного цикла (список портов, шимы PATH, chmod,
#  указатель статус-лайна, ожидание готовности) — и она разъехалась с виндовой:
#  bat знал 8 портов, этот файл 10, и «перезапустил» означало на маке и на Windows
#  разное. Всё уехало в routing/lifecycle.js, включая шимы и chmod.
#
#  Зовут отсюда: старые ярлыки и docs/MAC-SETUP.md.
#  Полное меню — HUB.command в корне.
# ─────────────────────────────────────────────────────────────────────────────
cd "$(cd "$(dirname "$0")/.." && pwd)" || exit 1

if ! command -v node >/dev/null 2>&1; then
  export PATH="/opt/homebrew/bin:/usr/local/bin:$PATH"
  [ -s "$HOME/.nvm/nvm.sh" ] && . "$HOME/.nvm/nvm.sh" >/dev/null 2>&1
fi

node hub.js restart "$@"
RC=$?

# DASHBOARD_WAIT_ENTER=1 ставил двойной клик по DASHBOARD.command: окно Terminal
# закрывается вместе с выводом. Флаг сохранён — на этот путь могли показывать чужие
# ярлыки. В обычном терминале пауза вредна: `read` съедает следующую строку
# вставленного блока команд (поймано живьём — пробник баланса «не запустился»,
# его строку прочитал этот read вместо Enter).
if [ -t 0 ] && [ "${DASHBOARD_WAIT_ENTER:-0}" = "1" ]; then
  read -r -p "Нажми Enter, чтобы закрыть окно... " _
fi
exit $RC
